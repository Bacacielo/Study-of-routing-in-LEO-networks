function artifacts = RunFreshHypatiaValidation( ...
        generationRoot, outputDirectory)
% RUNFRESHHYPATIAVALIDATION Validate all three freshly generated workloads.

projectRoot = fileparts(mfilename('fullpath'));
if nargin < 1 || isempty(generationRoot)
    error('FreshHypatiaValidation:MissingGenerationRoot', ...
        'Provide the Hypatia gen_data directory.');
end
if ~(ischar(generationRoot) || ...
        (isstring(generationRoot) && isscalar(generationRoot)))
    error('FreshHypatiaValidation:InvalidGenerationRoot', ...
        'Generation root must be a character vector or string scalar.');
end
generationRoot = char(generationRoot);
if ~isfolder(generationRoot)
    error('FreshHypatiaValidation:GenerationRootNotFound', ...
        'Generation root does not exist: %s', generationRoot);
end
if nargin < 2 || isempty(outputDirectory)
    outputDirectory = fullfile( ...
        projectRoot, 'outputs', 'hypatia_fresh_validation');
end
if ~(ischar(outputDirectory) || ...
        (isstring(outputDirectory) && isscalar(outputDirectory)))
    error('FreshHypatiaValidation:InvalidOutputDirectory', ...
        'Output directory must be a character vector or string scalar.');
end
outputDirectory = char(outputDirectory);
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

workloads = {
    'kuiper_k1', ...
    'kuiper_630_isls_plus_grid_ground_stations_top_100_algorithm_free_one_only_over_isls';
    'starlink_s1', ...
    'starlink_550_isls_plus_grid_ground_stations_top_100_algorithm_free_one_only_over_isls';
    'telesat_t1', ...
    'telesat_1015_isls_plus_grid_ground_stations_top_100_algorithm_free_one_only_over_isls'
};

summaries = cell(size(workloads, 1), 1);
validationArtifacts = cell(size(workloads, 1), 1);
for workloadIndex = 1:size(workloads, 1)
    constellationKey = workloads{workloadIndex, 1};
    satelliteNetworkDirectory = fullfile( ...
        generationRoot, workloads{workloadIndex, 2});
    constellationOutputDirectory = fullfile( ...
        outputDirectory, constellationKey);
    validationArtifacts{workloadIndex} = ...
        RunHypatiaStateValidation( ...
        satelliteNetworkDirectory, ...
        constellationKey, ...
        constellationOutputDirectory);
    summaries{workloadIndex} = ...
        validationArtifacts{workloadIndex}.SummaryTable;
end

combinedSummary = vertcat(summaries{:});
if any(combinedSummary.SnapshotCount ~= 2000) || ...
        any(combinedSummary.PairCount ~= 4950) || ...
        any(~combinedSummary.MatchesOfficialEcdfExactly) || ...
        any(combinedSummary.EcdfMismatchCount ~= 0)
    error('FreshHypatiaValidation:ComparisonFailed', ...
        'Fresh forwarding states did not reproduce all official ECDFs.');
end

summaryPath = fullfile( ...
    outputDirectory, 'hypatia_fresh_fstate_validation_all.csv');
matPath = fullfile( ...
    outputDirectory, 'hypatia_fresh_fstate_validation_all.mat');
writetable(combinedSummary, summaryPath);
save(matPath, ...
    'combinedSummary', ...
    'generationRoot', ...
    'validationArtifacts');

artifacts = struct( ...
    'GenerationRoot', generationRoot, ...
    'OutputDirectory', outputDirectory, ...
    'SummaryPath', summaryPath, ...
    'MatPath', matPath, ...
    'SummaryTable', combinedSummary, ...
    'ValidationArtifacts', {validationArtifacts});

disp('Fresh Hypatia fstate validation completed');
disp(combinedSummary);
disp(['Summary: ', summaryPath]);
end
