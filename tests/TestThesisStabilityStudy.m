classdef TestThesisStabilityStudy < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addSourcePath(~)
            testDirectory = fileparts(mfilename('fullpath'));
            addpath(fullfile(fileparts(testDirectory), 'src'));
        end
    end

    methods (Test)
        function runCaseReportsBoundedStabilityTradeoff(testCase)
            cfg = ThesisConfig.withOverrides(struct( ...
                'PlaneCount', 4, ...
                'SatellitesPerPlane', 8, ...
                'NodeCount', 32, ...
                'Seed', 23, ...
                'LinkQualityTimeMode', 'StaticByEdge', ...
                'ContactDutyCycle', 0.65, ...
                'ReliabilityWeight', 0.6, ...
                'SourceNode', 1, ...
                'DestinationNode', 16, ...
                'TimeSteps', 20));

            result = ThesisStabilityStudy.runCase(cfg, 0.10);

            testCase.verifyEqual(result.TimeSteps, 20);
            testCase.verifyGreaterThanOrEqual( ...
                result.OptimalRouteChanges, 0);
            testCase.verifyGreaterThanOrEqual( ...
                result.StableRouteChanges, 0);
            testCase.verifyTrue(result.HysteresisBoundRespected);
            testCase.verifyLessThanOrEqual( ...
                result.MaximumRetainedRelativeCostGap, ...
                0.10 + 1e-12);
        end

        function runCaseIsDeterministic(testCase)
            cfg = ThesisConfig.withOverrides(struct( ...
                'Seed', 42, ...
                'LinkQualityTimeMode', 'StaticByEdge', ...
                'TimeSteps', 12));

            first = ThesisStabilityStudy.runCase(cfg, 0.20);
            second = ThesisStabilityStudy.runCase(cfg, 0.20);

            testCase.verifyEqual( ...
                first.StableRouteChanges, ...
                second.StableRouteChanges);
            testCase.verifyEqual( ...
                first.StableMeanEffectiveLatencyMs, ...
                second.StableMeanEffectiveLatencyMs, ...
                'AbsTol', 1e-12);
        end

        function summarizeIdentifiesBudgetAndParetoRows(testCase)
            cfg = ThesisConfig.withOverrides(struct( ...
                'Seed', 11, ...
                'LinkQualityTimeMode', 'StaticByEdge', ...
                'TimeSteps', 12));
            tolerances = [0, 0.10, 0.20];
            rows = cell(numel(tolerances), 1);
            for toleranceIndex = 1:numel(tolerances)
                item = ThesisStabilityStudy.runCase( ...
                    cfg, tolerances(toleranceIndex));
                rows{toleranceIndex} = struct( ...
                    'HysteresisTolerance', ...
                    item.HysteresisTolerance, ...
                    'StableRouteChanges', ...
                    item.StableRouteChanges, ...
                    'OptimalRouteChanges', ...
                    item.OptimalRouteChanges, ...
                    'RouteChangesAvoided', ...
                    item.RouteChangesAvoided, ...
                    'RouteChangeReductionRate', ...
                    item.RouteChangeReductionRate, ...
                    'LatencyPenaltyMs', ...
                    item.LatencyPenaltyMs, ...
                    'AvailabilityDelta', ...
                    item.AvailabilityDelta, ...
                    'EffectiveLatencyPenaltyMs', ...
                    item.EffectiveLatencyPenaltyMs, ...
                    'RelativeEffectiveLatencyPenalty', ...
                    item.RelativeEffectiveLatencyPenalty, ...
                    'PreviousPathRetentionRate', ...
                    item.PreviousPathRetentionRate, ...
                    'MaximumRetainedRelativeCostGap', ...
                    item.MaximumRetainedRelativeCostGap);
            end

            summary = ThesisStabilityStudy.summarize( ...
                struct2table(vertcat(rows{:})));

            testCase.verifyEqual(summary.RowCount, 3);
            testCase.verifyTrue( ...
                any(summary.ByHysteresisTolerance.ParetoEfficient));
            testCase.verifyTrue( ...
                summary.AllCasesRespectHysteresisBound);
        end

        function invalidTimeHorizonIsRejected(testCase)
            cfg = ThesisConfig.withOverrides(struct('TimeSteps', 1));

            testCase.verifyError( ...
                @() ThesisStabilityStudy.runCase(cfg, 0.1), ...
                'ThesisStabilityStudy:InvalidTimeSteps');
        end
    end
end
