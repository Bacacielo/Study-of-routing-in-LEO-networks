classdef TestThesisResultsAnalysis < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addSourcePath(~)
            testDir = fileparts(mfilename('fullpath'));
            addpath(fullfile(fileparts(testDir), 'src'));
        end
    end

    methods (Test)
        function summarizeIdentifiesCoreTradeoff(testCase)
            results = table( ...
                [4; 4; 6], ...
                [8; 8; 12], ...
                [32; 32; 72], ...
                [0.45; 0.65; 0.85], ...
                [0.20; 0.35; 0.50], ...
                [0.3; 0.6; 0.9], ...
                [17; 14; 11], ...
                [21; 15; 12], ...
                [4; 1; 1], ...
                [54; 32; 20], ...
                [28; 17; 18], ...
                [26; 15; 2], ...
                [0.55; 0.65; 0.80], ...
                [0.81; 0.86; 0.88], ...
                [0.26; 0.21; 0.08], ...
                [8; 5; 2], ...
                [8; 3; 2], ...
                'VariableNames', { ...
                'PlaneCount', ...
                'SatellitesPerPlane', ...
                'NodeCount', ...
                'ContactDutyCycle', ...
                'ShortcutRiskAvailability', ...
                'ReliabilityWeight', ...
                'BaselineMeanLatencyMs', ...
                'ReliableMeanLatencyMs', ...
                'ReliableLatencyPenaltyMs', ...
                'BaselineMeanEffectiveLatencyMs', ...
                'ReliableMeanEffectiveLatencyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'BaselineMeanAvailability', ...
                'ReliableMeanAvailability', ...
                'ReliableAvailabilityGain', ...
                'BaselineRouteChanges', ...
                'ReliableRouteChanges'});

            summary = ThesisResultsAnalysis.summarize(results);

            testCase.verifyEqual(summary.RowCount, 3);
            testCase.verifyEqual(summary.BestEffectiveLatencyImprovementMs, 26);
            testCase.verifyEqual(summary.BestEffectiveLatencyCase.ReliabilityWeight, 0.3);
            testCase.verifyEqual(summary.MaxAvailabilityGain, 0.26, 'AbsTol', 1e-12);
            testCase.verifyGreaterThan(summary.PositiveEffectiveLatencyImprovementRate, 0.99);
            testCase.verifyTrue(isfield(summary, 'SensitivityByReliabilityWeight'));
            testCase.verifyEqual(summary.SensitivityByReliabilityWeight.GroupCount, [1; 1; 1]);
            testCase.verifyEqual(summary.SensitivityByReliabilityWeight.mean_ReliableAvailabilityGain(3), 0.08, 'AbsTol', 1e-12);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Positive, 3);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Zero, 0);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Negative, 0);
            testCase.verifyTrue(isfield(summary, 'SensitivityByConstellation'));
            testCase.verifyTrue(isfield(summary, 'RouteChangeStatistics'));
        end

        function summarizeReproducesChapterFourStatistics(testCase)
            results = ThesisExperimentSuite.runMatrix(ThesisExperimentSuite.defaultMatrix());

            summary = ThesisResultsAnalysis.summarize(results);

            testCase.verifyEqual(summary.AvailabilityGainStatistics.Std, 0.0755172715, 'AbsTol', 1e-10);
            testCase.verifyEqual(summary.EffectiveLatencyImprovementStatistics.Minimum, ...
                -3.019995341339, 'AbsTol', 1e-9);
            testCase.verifyEqual(summary.EffectiveLatencyImprovementStatistics.Maximum, ...
                28.833686911528, 'AbsTol', 1e-9);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Positive, 44);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Negative, 10);
            testCase.verifyEqual(summary.EffectiveLatencyOutcomeCounts.Zero, 27);
            testCase.verifyEqual(summary.LatencyPenaltyImprovementCorrelation, 0.3676485636, 'AbsTol', 1e-9);
            testCase.verifyEqual(summary.LatencyPenaltyImprovementCorrelationNonzero, ...
                0.130940523935, 'AbsTol', 1e-9);
            testCase.verifyEqual(summary.NonzeroTradeoffCaseCount, 54);
            testCase.verifyEqual(summary.RouteChangeStatistics.Delta.Mean, 0.5925925926, 'AbsTol', 1e-9);
            testCase.verifyEqual(summary.SensitivityByConstellation.mean_EffectiveLatencyImprovementMs, ...
                [6.4046; 10.0316; -0.4559], 'AbsTol', 5e-5);
        end

        function writeNotesCreatesMarkdownWithThesisClaims(testCase)
            results = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', [0.20 0.35], ...
                'ReliabilityWeights', [0.3 0.9], ...
                'TimeSteps', 3, ...
                'Seed', 11));
            summary = ThesisResultsAnalysis.summarize(results);
            outputPath = [tempname, '.md'];
            cleanup = onCleanup(@() delete(outputPath));

            ThesisResultsAnalysis.writeNotes(summary, outputPath);
            text = fileread(outputPath);

            testCase.verifyNotEmpty(text);
            testCase.verifyNotEmpty(strfind(text, 'Effective latency'));
            testCase.verifyNotEmpty(strfind(text, 'Thesis Claims'));
            testCase.verifyNotEmpty(strfind(text, 'Parameter Sensitivity'));
            testCase.verifyNotEmpty(strfind(text, 'Descriptive Statistics'));
            testCase.verifyNotEmpty(strfind(text, 'Route Stability'));
            testCase.verifyNotEmpty(strfind(text, 'Scope note'));
            clear cleanup;
        end

        function summarizeRobustnessProducesGroupedResults(testCase)
            mainResults = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', 0.35, ...
                'ReliabilityWeights', [0.3 0.9], ...
                'TimeSteps', 2, ...
                'Seeds', 42, ...
                'RoutePairs', [1 16]));
            seedResults = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', 0.35, ...
                'ReliabilityWeights', [0.3 0.9], ...
                'TimeSteps', 2, ...
                'Seeds', [11 23], ...
                'RoutePairs', [1 16]));
            pairResults = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', 0.35, ...
                'ReliabilityWeights', [0.3 0.9], ...
                'TimeSteps', 2, ...
                'Seeds', 42, ...
                'RoutePairs', [1 16; 2 17]));

            summary = ThesisResultsAnalysis.summarizeRobustness( ...
                mainResults, seedResults, pairResults);

            testCase.verifyEqual(height(summary.BySeed), 2);
            testCase.verifyEqual(height(summary.ByRoutePair), 2);
            testCase.verifyEqual(summary.SeedEffectiveLatency.Count, 4);
            testCase.verifyEqual(summary.RoutePairEffectiveLatency.Count, 4);
        end

        function summarizeTimeHorizonUsesComparableRouteChangeRates(testCase)
            matrix = struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', 0.35, ...
                'ReliabilityWeights', [0.3 0.9], ...
                'Seeds', 42, ...
                'RoutePairs', [1 16]);

            matrix.TimeSteps = 2;
            shortResults = ThesisExperimentSuite.runMatrix(matrix);
            matrix.TimeSteps = 4;
            longResults = ThesisExperimentSuite.runMatrix(matrix);

            summary = ThesisResultsAnalysis.summarizeTimeHorizon( ...
                [shortResults; longResults]);

            testCase.verifyEqual(summary.RowCount, 4);
            testCase.verifyEqual(summary.ByTimeSteps.TimeSteps, [2; 4]);
            testCase.verifyEqual(summary.ByTimeSteps.GroupCount, [2; 2]);
            testCase.verifyGreaterThanOrEqual( ...
                summary.ByTimeSteps.mean_BaselineRouteChangeRate, 0);
            testCase.verifyLessThanOrEqual( ...
                summary.ByTimeSteps.mean_BaselineRouteChangeRate, 1);
            testCase.verifyGreaterThanOrEqual( ...
                summary.ByTimeSteps.mean_ReliableRouteChangeRate, 0);
            testCase.verifyLessThanOrEqual( ...
                summary.ByTimeSteps.mean_ReliableRouteChangeRate, 1);
            testCase.verifyEqual(summary.LongestTimeHorizon, 4);
        end

        function summarizeControlledConstellationUsesConfiguredEndpoints(testCase)
            results = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8; 6 12], ...
                'ContactDutyCycles', 0.65, ...
                'ShortcutRiskAvailabilities', 0.35, ...
                'ReliabilityWeights', 0.6, ...
                'TimeSteps', 3, ...
                'Seeds', 11, ...
                'RoutePairs', [1 13; 1 19]));

            summary = ThesisResultsAnalysis.summarizeControlledConstellation(results);

            testCase.verifyEqual(summary.RowCount, 4);
            testCase.verifyEqual(height(summary.ByConstellation), 4);
            testCase.verifyEqual(unique(summary.ByConstellation.DestinationNode), [13; 19]);
        end

        function summarizeTopologyOnlyAblationIdentifiesStaticControl(testCase)
            results = table( ...
                [0.65; 0.65; 1; 1], ...
                [0.3; 0.4; 0; 0], ...
                [0.2; 0.5; 0; 0], ...
                'VariableNames', { ...
                'ContactDutyCycle', ...
                'BaselineRouteChangeRate', ...
                'ReliableRouteChangeRate'});

            summary = ThesisResultsAnalysis.summarizeTopologyOnlyAblation(results);

            testCase.verifyEqual(summary.RowCount, 4);
            testCase.verifyTrue(summary.DynamicContactProducesRouteChanges);
            testCase.verifyTrue(summary.StaticControlHasNoRouteChanges);
        end

        function writeFiguresCreatesExpectedPngFiles(testCase)
            results = ThesisExperimentSuite.runMatrix(struct( ...
                'Constellations', [4 8], ...
                'ContactDutyCycles', [0.45 0.65], ...
                'ShortcutRiskAvailabilities', [0.20 0.35], ...
                'ReliabilityWeights', [0.3 0.9], ...
                'TimeSteps', 3, ...
                'Seed', 11));
            outputDir = tempname;
            mkdir(outputDir);
            cleanup = onCleanup(@() rmdir(outputDir, 's'));

            figurePaths = ThesisResultsAnalysis.writeFigures(results, outputDir);

            testCase.verifyTrue(isfile(figurePaths.ReliabilityWeightSensitivity));
            testCase.verifyTrue(isfile(figurePaths.EffectiveLatencyByRisk));
            testCase.verifyTrue(isfile(figurePaths.LatencyTradeoff));
            testCase.verifyTrue(isfile(figurePaths.RouteChangesComparison));
            clear cleanup;
        end
    end
end
