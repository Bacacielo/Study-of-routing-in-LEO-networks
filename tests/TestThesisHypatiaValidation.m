classdef TestThesisHypatiaValidation < matlab.unittest.TestCase
    methods (TestClassSetup)
        function addSourcePath(~)
            testDirectory = fileparts(mfilename('fullpath'));
            projectRoot = fileparts(testDirectory);
            addpath(projectRoot);
            addpath(fullfile(projectRoot, 'src'));
        end
    end

    methods (Test)
        function officialDataReproducePublishedAnchors(testCase)
            summary = ThesisHypatiaValidation.analyze();
            results = summary.Table;

            testCase.verifyTrue(summary.PaperAnchorsVerified);
            testCase.verifyEqual(height(results), 3);
            testCase.verifyEqual(results.PairCount, [4950; 4950; 4950]);
            testCase.verifyEqual(results.MedianPathChanges, [4; 4; 2]);
            testCase.verifyGreaterThan( ...
                results.FractionAtLeast7PathChanges(1), 0.10);
            testCase.verifyGreaterThan( ...
                results.FractionAtLeast7PathChanges(2), 0.10);
            testCase.verifyEqual( ...
                results.MedianRttRangeMs(2), ...
                10.175954022548115, ...
                'AbsTol', 1e-12);
        end

        function matlabSummaryMatchesIndependentPythonSummary(testCase)
            testDirectory = fileparts(mfilename('fullpath'));
            projectRoot = fileparts(testDirectory);
            pythonSummaryPath = fullfile( ...
                projectRoot, 'reproducibility', 'hypatia', ...
                'official_results.json');
            pythonSummary = jsondecode(fileread(pythonSummaryPath));
            matlabSummary = ThesisHypatiaValidation.analyze();

            expectedMedianRtt = [ ...
                pythonSummary.constellations.kuiper_k1. ...
                rtt_max_minus_min_ms.median; ...
                pythonSummary.constellations.starlink_s1. ...
                rtt_max_minus_min_ms.median; ...
                pythonSummary.constellations.telesat_t1. ...
                rtt_max_minus_min_ms.median];
            expectedMeanPathChanges = [ ...
                pythonSummary.constellations.kuiper_k1.path_changes.mean; ...
                pythonSummary.constellations.starlink_s1.path_changes.mean; ...
                pythonSummary.constellations.telesat_t1.path_changes.mean];

            testCase.verifyEqual( ...
                matlabSummary.Table.MedianRttRangeMs, ...
                expectedMedianRtt, ...
                'AbsTol', 1e-12);
            testCase.verifyEqual( ...
                matlabSummary.Table.MeanPathChanges, ...
                expectedMeanPathChanges, ...
                'AbsTol', 1e-12);
        end

        function exportCreatesAuditableArtifacts(testCase)
            outputDirectory = fullfile( ...
                tempdir, ['hypatia-validation-', ...
                char(java.util.UUID.randomUUID())]);
            cleanup = onCleanup(@() ...
                TestThesisHypatiaValidation.removeDirIfPresent( ...
                outputDirectory));

            summary = ThesisHypatiaValidation.analyze();
            artifacts = ThesisHypatiaValidation.export( ...
                summary, outputDirectory);

            testCase.verifyTrue(isfile(artifacts.SummaryCsvPath));
            testCase.verifyTrue(isfile(artifacts.EcdfFigurePath));
            testCase.verifyGreaterThan( ...
                dir(artifacts.EcdfFigurePath).bytes, 10 * 1024);
            exportedTable = readtable(artifacts.SummaryCsvPath, ...
                'TextType', 'string');
            testCase.verifyEqual(height(exportedTable), 3);
            clear cleanup;
        end

        function malformedEcdfIsRejected(testCase)
            sourceRoot = ThesisHypatiaValidation.defaultDataRoot();
            temporaryRoot = fullfile( ...
                tempdir, ['hypatia-invalid-', ...
                char(java.util.UUID.randomUUID())]);
            cleanup = onCleanup(@() ...
                TestThesisHypatiaValidation.removeDirIfPresent(temporaryRoot));
            copyfile(sourceRoot, temporaryRoot);

            invalidPath = fullfile(temporaryRoot, 'kuiper_k1', ...
                'ecdf_pairs_num_path_changes.txt');
            fileId = fopen(invalidPath, 'w');
            fileCleanup = onCleanup(@() fclose(fileId));
            fprintf(fileId, '-inf,0.0\n2.0,0.5\n1.0,1.0\n');
            clear fileCleanup;

            testCase.verifyError( ...
                @() ThesisHypatiaValidation.analyze(temporaryRoot), ...
                'ThesisHypatiaValidation:InvalidEcdf');
            clear cleanup;
        end
    end

    methods (Static, Access = private)
        function removeDirIfPresent(pathToRemove)
            if isfolder(pathToRemove)
                rmdir(pathToRemove, 's');
            end
        end
    end
end
