function artifacts = RunHypatiaStateValidation( ...
        satelliteNetworkDirectory, constellationKey, outputDirectory)
% RUNHYPATIASTATEVALIDATION Recompute Hypatia route changes from fstate.

projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'src'));
if nargin < 2
    error('HypatiaStateValidation:MissingInput', ...
        ['Provide a generated Hypatia satellite-network directory and ' ...
        'one of: kuiper_k1, starlink_s1, or telesat_t1.']);
end
if ~(ischar(constellationKey) || ...
        (isstring(constellationKey) && isscalar(constellationKey)))
    error('HypatiaStateValidation:InvalidConstellationKey', ...
        'Constellation key must be a character vector or string scalar.');
end
constellationKey = char(constellationKey);
validKeys = {'kuiper_k1', 'starlink_s1', 'telesat_t1'};
if ~ismember(constellationKey, validKeys)
    error('HypatiaStateValidation:InvalidConstellationKey', ...
        'Constellation key must be kuiper_k1, starlink_s1, or telesat_t1.');
end
if nargin < 3 || isempty(outputDirectory)
    outputDirectory = fullfile( ...
        projectRoot, 'outputs', 'hypatia_state_validation', ...
        constellationKey);
end
if ~(ischar(outputDirectory) || ...
        (isstring(outputDirectory) && isscalar(outputDirectory)))
    error('HypatiaStateValidation:InvalidOutputDirectory', ...
        'Output directory must be a character vector or string scalar.');
end
outputDirectory = char(outputDirectory);
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

stateResult = ThesisHypatiaStateAnalyzer.analyzeRouteChanges( ...
    satelliteNetworkDirectory, 100, 200, 100);
referenceEcdfPath = fullfile( ...
    projectRoot, 'reproducibility', 'hypatia', ...
    'official_data', constellationKey, ...
    'ecdf_pairs_num_path_changes.txt');
comparison = ThesisHypatiaStateAnalyzer.compareRouteChangeEcdf( ...
    stateResult, referenceEcdfPath);

pairTablePath = fullfile( ...
    outputDirectory, 'hypatia_fstate_pair_route_changes.csv');
summaryPath = fullfile( ...
    outputDirectory, 'hypatia_fstate_validation_summary.csv');
writetable(stateResult.PairTable, pairTablePath);
summaryTable = table( ...
    string(constellationKey), ...
    stateResult.SatelliteCount, ...
    stateResult.GroundStationCount, ...
    stateResult.SnapshotCount, ...
    height(stateResult.PairTable), ...
    stateResult.MedianRouteChanges, ...
    stateResult.MeanRouteChanges, ...
    stateResult.P90RouteChanges, ...
    stateResult.P95RouteChanges, ...
    stateResult.FractionAtLeast7RouteChanges, ...
    comparison.MatchesExactly, ...
    comparison.MismatchCount, ...
    'VariableNames', { ...
    'ConstellationKey', ...
    'SatelliteCount', ...
    'GroundStationCount', ...
    'SnapshotCount', ...
    'PairCount', ...
    'MedianRouteChanges', ...
    'MeanRouteChanges', ...
    'P90RouteChanges', ...
    'P95RouteChanges', ...
    'FractionAtLeast7RouteChanges', ...
    'MatchesOfficialEcdfExactly', ...
    'EcdfMismatchCount'});
writetable(summaryTable, summaryPath);

artifacts = struct( ...
    'OutputDirectory', outputDirectory, ...
    'PairTablePath', pairTablePath, ...
    'SummaryPath', summaryPath, ...
    'SummaryTable', summaryTable, ...
    'Comparison', comparison, ...
    'StateResult', stateResult);

disp('Hypatia fstate validation completed');
disp(summaryTable);
disp(['Pair table: ', pairTablePath]);
disp(['Summary: ', summaryPath]);
end
