function artifacts = RunFullThesisStudy( ...
        outputDirectory, stabilityStudyDesign)
% RUNFULLTHESISSTUDY Reproduce all thesis experiments and analysis outputs.

projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'src'));
if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile(projectRoot, 'outputs');
end
if nargin < 2 || isempty(stabilityStudyDesign)
    stabilityStudyDesign = struct();
end
if ~(ischar(outputDirectory) || (isstring(outputDirectory) && isscalar(outputDirectory)))
    error('ThesisStudy:InvalidOutputDirectory', ...
        'Output directory must be a character vector or string scalar.');
end
outputDir = char(outputDirectory);

matrix = ThesisExperimentSuite.defaultMatrix(); %#ok<NASGU>
run(fullfile(projectRoot, 'RunExperimentSuite.m'));
mainRowCount = height(results);

seedMatrix = []; %#ok<NASGU>
routePairMatrix = []; %#ok<NASGU>
run(fullfile(projectRoot, 'RunRobustnessSuite.m'));
seedRowCount = height(results);
routePairRowCount = height(routePairResults);

timeHorizonMatrix = []; %#ok<NASGU>
timeHorizons = []; %#ok<NASGU>
run(fullfile(projectRoot, 'RunTimeHorizonSensitivity.m'));
timeHorizonRowCount = height(timeHorizonResults);

controlledConstellationMatrix = []; %#ok<NASGU>
run(fullfile(projectRoot, 'RunControlledConstellationSensitivity.m'));
controlledConstellationRowCount = height(controlledConstellationResults);

topologyAblationSeeds = []; %#ok<NASGU>
topologyAblationDutyCycles = []; %#ok<NASGU>
topologyAblationTimeSteps = []; %#ok<NASGU>
run(fullfile(projectRoot, 'RunTopologyOnlyAblation.m'));
topologyOnlyAblationRowCount = height(topologyOnlyAblationResults);

reliabilityStressSweep = []; %#ok<NASGU>
run(fullfile(projectRoot, 'RunReliabilityStressAblation.m'));
reliabilityStressAblationRowCount = ...
    height(reliabilityStressAblationResults);

hypatiaValidationArtifacts = RunHypatiaValidation( ...
    fullfile(outputDir, 'hypatia_validation'));
stabilityAwareArtifacts = RunStabilityAwareAblation( ...
    outputDir, stabilityStudyDesign);

summary = [];
robustnessSummary = [];
timeHorizonSummary = [];
controlledConstellationAnalysis = [];
topologyOnlyAblationAnalysis = [];
reliabilityStressAblationAnalysis = [];
figurePaths = struct();
notesPath = '';
summaryMatPath = '';
run(fullfile(projectRoot, 'AnalyzeExperimentResults.m'));

artifacts = struct( ...
    'OutputDirectory', outputDir, ...
    'MainResultsPath', fullfile(outputDir, 'experiment_results.csv'), ...
    'SeedResultsPath', fullfile(outputDir, 'robustness_seed_results.csv'), ...
    'RoutePairResultsPath', fullfile(outputDir, 'robustness_route_pair_results.csv'), ...
    'TimeHorizonResultsPath', fullfile(outputDir, 'time_horizon_sensitivity_results.csv'), ...
    'ControlledConstellationResultsPath', fullfile(outputDir, 'controlled_constellation_sensitivity_results.csv'), ...
    'TopologyOnlyAblationResultsPath', fullfile(outputDir, 'topology_only_ablation_results.csv'), ...
    'ReliabilityStressAblationResultsPath', fullfile(outputDir, 'reliability_stress_ablation_results.csv'), ...
    'NotesPath', notesPath, ...
    'AnalysisSummaryPath', summaryMatPath, ...
    'FigurePaths', figurePaths, ...
    'MainRowCount', mainRowCount, ...
    'SeedRowCount', seedRowCount, ...
    'RoutePairRowCount', routePairRowCount, ...
    'TimeHorizonRowCount', timeHorizonRowCount, ...
    'ControlledConstellationRowCount', controlledConstellationRowCount, ...
    'TopologyOnlyAblationRowCount', topologyOnlyAblationRowCount, ...
    'ReliabilityStressAblationRowCount', reliabilityStressAblationRowCount, ...
    'HypatiaValidation', hypatiaValidationArtifacts, ...
    'StabilityAwareAblation', stabilityAwareArtifacts, ...
    'Summary', summary, ...
    'RobustnessSummary', robustnessSummary, ...
    'TimeHorizonSummary', timeHorizonSummary, ...
    'ControlledConstellationAnalysis', controlledConstellationAnalysis, ...
    'TopologyOnlyAblationAnalysis', topologyOnlyAblationAnalysis, ...
    'ReliabilityStressAblationAnalysis', reliabilityStressAblationAnalysis);
end
