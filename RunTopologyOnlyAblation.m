projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'src'));

if ~exist('outputDir', 'var') || isempty(outputDir)
    outputDir = fullfile(projectRoot, 'outputs');
end
if ~isfolder(outputDir)
    mkdir(outputDir);
end

if ~exist('topologyAblationSeeds', 'var') || isempty(topologyAblationSeeds)
    topologyAblationSeeds = [11 23 42 77 101];
end
if ~exist('topologyAblationDutyCycles', 'var') || ...
        isempty(topologyAblationDutyCycles)
    topologyAblationDutyCycles = [0.45 0.65 0.85 1.00];
end
if ~exist('topologyAblationTimeSteps', 'var') || ...
        isempty(topologyAblationTimeSteps)
    topologyAblationTimeSteps = 100;
end

seeds = topologyAblationSeeds;
contactDutyCycles = topologyAblationDutyCycles;
timeSteps = topologyAblationTimeSteps;
rowCount = numel(seeds) * numel(contactDutyCycles);
rows = repmat(struct( ...
    'Seed', 0, ...
    'PlaneCount', 6, ...
    'SatellitesPerPlane', 12, ...
    'SourceNode', 1, ...
    'DestinationNode', 19, ...
    'ContactDutyCycle', 0, ...
    'TimeSteps', timeSteps, ...
    'BaselineRouteChanges', 0, ...
    'ReliableRouteChanges', 0, ...
    'BaselineRouteChangeRate', 0, ...
    'ReliableRouteChangeRate', 0), rowCount, 1);

rowIndex = 1;
for seed = seeds
    for dutyCycle = contactDutyCycles
        cfg = ThesisConfig.withOverrides(struct( ...
            'PlaneCount', 6, ...
            'SatellitesPerPlane', 12, ...
            'NodeCount', 72, ...
            'Seed', seed, ...
            'LinkQualityTimeMode', 'StaticByEdge', ...
            'ContactDutyCycle', dutyCycle, ...
            'ShortcutRiskAvailability', 0.35, ...
            'ReliabilityWeight', 0.60, ...
            'SourceNode', 1, ...
            'DestinationNode', 19, ...
            'TimeSteps', timeSteps));
        result = ThesisScenarioRunner.runTimeSeries(cfg);
        transitionCount = timeSteps - 1;

        rows(rowIndex).Seed = seed;
        rows(rowIndex).ContactDutyCycle = dutyCycle;
        rows(rowIndex).BaselineRouteChanges = result.Summary.BaselineRouteChanges;
        rows(rowIndex).ReliableRouteChanges = result.Summary.ReliableRouteChanges;
        rows(rowIndex).BaselineRouteChangeRate = ...
            result.Summary.BaselineRouteChanges / transitionCount;
        rows(rowIndex).ReliableRouteChangeRate = ...
            result.Summary.ReliableRouteChanges / transitionCount;
        rowIndex = rowIndex + 1;
    end
end

topologyOnlyAblationResults = struct2table(rows);
topologyOnlyAblationCsvPath = fullfile( ...
    outputDir, 'topology_only_ablation_results.csv');
topologyOnlyAblationMatPath = fullfile( ...
    outputDir, 'topology_only_ablation_results.mat');
writetable(topologyOnlyAblationResults, topologyOnlyAblationCsvPath);
save(topologyOnlyAblationMatPath, ...
    'topologyOnlyAblationResults', 'seeds', 'contactDutyCycles', 'timeSteps');

topologyOnlyAblationSummary = groupsummary( ...
    topologyOnlyAblationResults, 'ContactDutyCycle', {'mean', 'std'}, { ...
    'BaselineRouteChangeRate', 'ReliableRouteChangeRate'});

disp('Topology-only route-variability ablation completed');
disp(['Rows: ', num2str(height(topologyOnlyAblationResults))]);
disp(['CSV: ', topologyOnlyAblationCsvPath]);
disp(['MAT: ', topologyOnlyAblationMatPath]);
disp(topologyOnlyAblationSummary);
