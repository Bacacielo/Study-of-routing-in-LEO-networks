function artifacts = RunStabilityAwareAblation( ...
        outputDirectory, studyDesign)
% RUNSTABILITYAWAREABLATION Evaluate route hysteresis tradeoffs.

projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'src'));
if nargin < 1 || isempty(outputDirectory)
    outputDirectory = fullfile(projectRoot, 'outputs');
end
if nargin < 2 || isempty(studyDesign)
    studyDesign = struct();
end
if ~(ischar(outputDirectory) || ...
        (isstring(outputDirectory) && isscalar(outputDirectory)))
    error('StabilityAblation:InvalidOutputDirectory', ...
        'Output directory must be a character vector or string scalar.');
end
if ~isstruct(studyDesign) || ~isscalar(studyDesign)
    error('StabilityAblation:InvalidStudyDesign', ...
        'Study design must be a scalar structure.');
end
outputDirectory = char(outputDirectory);
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

design = applyDefaults(studyDesign);
validateDesign(design);
rowCount = ...
    numel(design.Seeds) * ...
    size(design.RoutePairs, 1) * ...
    numel(design.ContactDutyCycles) * ...
    numel(design.ReliabilityWeights) * ...
    numel(design.HysteresisTolerances);
rows = cell(rowCount, 1);
rowIndex = 1;

for seed = design.Seeds
    for routeIndex = 1:size(design.RoutePairs, 1)
        sourceNode = design.RoutePairs(routeIndex, 1);
        destinationNode = design.RoutePairs(routeIndex, 2);
        for dutyCycle = design.ContactDutyCycles
            for reliabilityWeight = design.ReliabilityWeights
                for hysteresisTolerance = ...
                        design.HysteresisTolerances
                    cfg = ThesisConfig.withOverrides(struct( ...
                        'PlaneCount', 6, ...
                        'SatellitesPerPlane', 12, ...
                        'NodeCount', 72, ...
                        'Seed', seed, ...
                        'LinkQualityTimeMode', 'StaticByEdge', ...
                        'ContactDutyCycle', dutyCycle, ...
                        'ReliabilityStressMode', ...
                        'InterPlaneShortcutRisk', ...
                        'ShortcutRiskAvailability', 0.35, ...
                        'ReliabilityWeight', reliabilityWeight, ...
                        'SourceNode', sourceNode, ...
                        'DestinationNode', destinationNode, ...
                        'TimeSteps', design.TimeSteps));
                    item = ThesisStabilityStudy.runCase( ...
                        cfg, hysteresisTolerance);
                    rows{rowIndex} = resultRow( ...
                        item, seed, sourceNode, destinationNode, ...
                        dutyCycle, reliabilityWeight);
                    rowIndex = rowIndex + 1;
                    completedRows = rowIndex - 1;
                    if mod(completedRows, 25) == 0 || ...
                            completedRows == rowCount
                        fprintf( ...
                            'Stability ablation: %d / %d cases\n', ...
                            completedRows, rowCount);
                    end
                end
            end
        end
    end
end

stabilityAwareResults = struct2table(vertcat(rows{:}));
stabilityAwareSummary = ...
    ThesisStabilityStudy.summarize(stabilityAwareResults);
resultsPath = fullfile( ...
    outputDirectory, 'stability_aware_ablation_results.csv');
summaryPath = fullfile( ...
    outputDirectory, 'stability_aware_by_hysteresis.csv');
matPath = fullfile( ...
    outputDirectory, 'stability_aware_ablation_results.mat');
figureDirectory = fullfile(outputDirectory, 'figures');
if ~isfolder(figureDirectory)
    mkdir(figureDirectory);
end
figurePath = fullfile( ...
    figureDirectory, 'stability_aware_hysteresis_tradeoff.png');

writetable(stabilityAwareResults, resultsPath);
writetable( ...
    stabilityAwareSummary.ByHysteresisTolerance, summaryPath);
save(matPath, ...
    'stabilityAwareResults', ...
    'stabilityAwareSummary', ...
    'design');
createTradeoffFigure( ...
    stabilityAwareSummary.ByHysteresisTolerance, figurePath);

artifacts = struct( ...
    'OutputDirectory', outputDirectory, ...
    'ResultsPath', resultsPath, ...
    'SummaryPath', summaryPath, ...
    'MatPath', matPath, ...
    'FigurePath', figurePath, ...
    'RowCount', height(stabilityAwareResults), ...
    'Results', stabilityAwareResults, ...
    'Summary', stabilityAwareSummary, ...
    'Design', design);

disp('Stability-aware hysteresis ablation completed');
disp(['Rows: ', num2str(height(stabilityAwareResults))]);
disp(stabilityAwareSummary.ByHysteresisTolerance);
if ~isempty( ...
        stabilityAwareSummary. ...
        BestUnderOnePercentEffectiveLatencyBudget)
    disp('Best row under the pre-specified 1% effective-latency budget:');
    disp(stabilityAwareSummary. ...
        BestUnderOnePercentEffectiveLatencyBudget);
end
disp(['CSV: ', resultsPath]);
disp(['Figure: ', figurePath]);
end

function design = applyDefaults(overrides)
design = struct( ...
    'Seeds', [11 23 42 77 101], ...
    'RoutePairs', [1 19; 2 25; 7 43], ...
    'ContactDutyCycles', [0.45 0.65 0.85], ...
    'ReliabilityWeights', [0.40 0.60 0.80], ...
    'HysteresisTolerances', [0 0.05 0.10 0.20 0.40], ...
    'TimeSteps', 100);
names = fieldnames(overrides);
for fieldIndex = 1:numel(names)
    if ~isfield(design, names{fieldIndex})
        error('StabilityAblation:UnknownDesignField', ...
            'Unknown study-design field: %s', names{fieldIndex});
    end
    design.(names{fieldIndex}) = overrides.(names{fieldIndex});
end
end

function validateDesign(design)
validateIntegerVector(design.Seeds, 'Seeds', 0);
if ~isnumeric(design.RoutePairs) || ...
        size(design.RoutePairs, 2) ~= 2 || ...
        isempty(design.RoutePairs) || ...
        any(~isfinite(design.RoutePairs), 'all') || ...
        any(design.RoutePairs ~= floor(design.RoutePairs), 'all') || ...
        any(design.RoutePairs < 1 | design.RoutePairs > 72, 'all') || ...
        any(design.RoutePairs(:, 1) == design.RoutePairs(:, 2))
    error('StabilityAblation:InvalidRoutePairs', ...
        ['RoutePairs must be a nonempty two-column matrix of ' ...
        'different node identifiers in [1, 72].']);
end
validateUnitIntervalVector( ...
    design.ContactDutyCycles, 'ContactDutyCycles', false);
validateUnitIntervalVector( ...
    design.ReliabilityWeights, 'ReliabilityWeights', true);
if ~isnumeric(design.HysteresisTolerances) || ...
        ~isvector(design.HysteresisTolerances) || ...
        isempty(design.HysteresisTolerances) || ...
        any(~isfinite(design.HysteresisTolerances)) || ...
        any(design.HysteresisTolerances < 0)
    error('StabilityAblation:InvalidHysteresisTolerances', ...
        'Hysteresis tolerances must be finite nonnegative values.');
end
if ~isnumeric(design.TimeSteps) || ...
        ~isscalar(design.TimeSteps) || ...
        ~isfinite(design.TimeSteps) || ...
        design.TimeSteps < 2 || ...
        design.TimeSteps ~= floor(design.TimeSteps)
    error('StabilityAblation:InvalidTimeSteps', ...
        'TimeSteps must be an integer of at least two.');
end
end

function validateIntegerVector(values, valueName, minimumValue)
if ~isnumeric(values) || ~isvector(values) || isempty(values) || ...
        any(~isfinite(values)) || ...
        any(values ~= floor(values)) || ...
        any(values < minimumValue)
    error('StabilityAblation:InvalidIntegerVector', ...
        '%s must be a nonempty integer vector.', valueName);
end
end

function validateUnitIntervalVector(values, valueName, allowZero)
lowerBound = 0;
if ~allowZero
    lowerBound = realmin;
end
if ~isnumeric(values) || ~isvector(values) || isempty(values) || ...
        any(~isfinite(values)) || ...
        any(values < lowerBound) || any(values > 1)
    error('StabilityAblation:InvalidUnitIntervalVector', ...
        '%s must contain values in the required unit interval.', ...
        valueName);
end
end

function row = resultRow( ...
        item, seed, sourceNode, destinationNode, ...
        dutyCycle, reliabilityWeight)
row = struct( ...
    'Seed', seed, ...
    'SourceNode', sourceNode, ...
    'DestinationNode', destinationNode, ...
    'ContactDutyCycle', dutyCycle, ...
    'ReliabilityWeight', reliabilityWeight, ...
    'HysteresisTolerance', item.HysteresisTolerance, ...
    'TimeSteps', item.TimeSteps, ...
    'OptimalMeanLatencyMs', item.OptimalMeanLatencyMs, ...
    'StableMeanLatencyMs', item.StableMeanLatencyMs, ...
    'LatencyPenaltyMs', item.LatencyPenaltyMs, ...
    'OptimalMeanAvailability', item.OptimalMeanAvailability, ...
    'StableMeanAvailability', item.StableMeanAvailability, ...
    'AvailabilityDelta', item.AvailabilityDelta, ...
    'OptimalMeanEffectiveLatencyMs', ...
    item.OptimalMeanEffectiveLatencyMs, ...
    'StableMeanEffectiveLatencyMs', ...
    item.StableMeanEffectiveLatencyMs, ...
    'EffectiveLatencyPenaltyMs', ...
    item.EffectiveLatencyPenaltyMs, ...
    'RelativeEffectiveLatencyPenalty', ...
    item.RelativeEffectiveLatencyPenalty, ...
    'OptimalRouteChanges', item.OptimalRouteChanges, ...
    'StableRouteChanges', item.StableRouteChanges, ...
    'OptimalRouteChangeRate', item.OptimalRouteChangeRate, ...
    'StableRouteChangeRate', item.StableRouteChangeRate, ...
    'RouteChangesAvoided', item.RouteChangesAvoided, ...
    'RouteChangeReductionRate', item.RouteChangeReductionRate, ...
    'PreviousPathRetentionCount', ...
    item.PreviousPathRetentionCount, ...
    'PreviousPathRetentionRate', ...
    item.PreviousPathRetentionRate, ...
    'UnavailableSwitchCount', item.UnavailableSwitchCount, ...
    'CostGapSwitchCount', item.CostGapSwitchCount, ...
    'MaximumRetainedRelativeCostGap', ...
    item.MaximumRetainedRelativeCostGap, ...
    'HysteresisBoundRespected', item.HysteresisBoundRespected);
end

function createTradeoffFigure(grouped, figurePath)
figureHandle = figure( ...
    'Visible', 'off', ...
    'Color', 'white', ...
    'Position', [100 100 1120 460]);
figureCleanup = onCleanup(@() close(figureHandle));
layout = tiledlayout(figureHandle, 1, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

routeAxes = nexttile(layout);
errorbar(routeAxes, ...
    grouped.HysteresisTolerance, ...
    grouped.mean_StableRouteChanges, ...
    grouped.std_StableRouteChanges, ...
    '-o', 'LineWidth', 1.6, 'MarkerFaceColor', [0 0.4470 0.7410]);
hold(routeAxes, 'on');
plot(routeAxes, ...
    grouped.HysteresisTolerance, ...
    grouped.mean_OptimalRouteChanges, ...
    '--', 'LineWidth', 1.4, 'Color', [0.25 0.25 0.25]);
grid(routeAxes, 'on');
xlabel(routeAxes, 'Hysteresis tolerance');
ylabel(routeAxes, 'Mean route changes');
title(routeAxes, 'Route stability');
legend(routeAxes, {'Stability-aware', 'Per-snapshot optimum'}, ...
    'Location', 'best');

penaltyAxes = nexttile(layout);
errorbar(penaltyAxes, ...
    grouped.HysteresisTolerance, ...
    100 .* grouped.mean_RelativeEffectiveLatencyPenalty, ...
    100 .* grouped.std_RelativeEffectiveLatencyPenalty, ...
    '-o', 'LineWidth', 1.6, ...
    'MarkerFaceColor', [0.8500 0.3250 0.0980]);
hold(penaltyAxes, 'on');
yline(penaltyAxes, 1, '--', '1% design budget', ...
    'LineWidth', 1.2);
penaltyMeans = ...
    100 .* grouped.mean_RelativeEffectiveLatencyPenalty;
penaltyStandardDeviations = ...
    100 .* grouped.std_RelativeEffectiveLatencyPenalty;
penaltyLower = min([0; penaltyMeans - penaltyStandardDeviations]);
penaltyUpper = max([1; penaltyMeans + penaltyStandardDeviations]);
penaltyMargin = 0.08 .* max(penaltyUpper - penaltyLower, 1);
ylim(penaltyAxes, ...
    [penaltyLower - penaltyMargin, penaltyUpper + penaltyMargin]);
grid(penaltyAxes, 'on');
xlabel(penaltyAxes, 'Hysteresis tolerance');
ylabel(penaltyAxes, 'Mean relative effective-latency penalty (%)');
title(penaltyAxes, 'Cost of stability');

title(layout, ...
    'Stability-aware routing: controlled hysteresis tradeoff');
allAxes = [routeAxes, penaltyAxes];
for axesHandle = allAxes
    axesHandle.FontName = 'Times New Roman';
    axesHandle.FontSize = 11;
    box(axesHandle, 'on');
end
exportgraphics(figureHandle, figurePath, 'Resolution', 200);
clear figureCleanup;
end
