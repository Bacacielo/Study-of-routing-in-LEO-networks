classdef ThesisHypatiaStateAnalyzer
    % THESISHYPATIASTATEANALYZER - Reconstruct routes from Hypatia fstate.

    methods (Static)
        function result = analyzeRouteChanges( ...
                satelliteNetworkDirectory, snapshotIntervalMs, ...
                durationSeconds, progressInterval)
            if nargin < 4 || isempty(progressInterval)
                progressInterval = 0;
            end
            satelliteNetworkDirectory = ...
                ThesisHypatiaStateAnalyzer.validateDirectoryArgument( ...
                satelliteNetworkDirectory);
            ThesisHypatiaStateAnalyzer.validatePositiveInteger( ...
                snapshotIntervalMs, 'SnapshotIntervalMs');
            ThesisHypatiaStateAnalyzer.validatePositiveInteger( ...
                durationSeconds, 'DurationSeconds');
            ThesisHypatiaStateAnalyzer.validateNonnegativeInteger( ...
                progressInterval, 'ProgressInterval');

            tlesPath = fullfile(satelliteNetworkDirectory, 'tles.txt');
            groundStationsPath = fullfile( ...
                satelliteNetworkDirectory, 'ground_stations.txt');
            if ~isfile(tlesPath) || ~isfile(groundStationsPath)
                error('ThesisHypatiaStateAnalyzer:MissingStaticData', ...
                    ['The satellite-network directory must contain ' ...
                    'tles.txt and ground_stations.txt.']);
            end

            satelliteCount = ...
                ThesisHypatiaStateAnalyzer.readSatelliteCount(tlesPath);
            groundStationCount = ...
                ThesisHypatiaStateAnalyzer.countGroundStations( ...
                groundStationsPath);
            nodeCount = satelliteCount + groundStationCount;
            if groundStationCount < 2
                error('ThesisHypatiaStateAnalyzer:TooFewGroundStations', ...
                    'At least two ground stations are required.');
            end

            dynamicStateDirectory = fullfile( ...
                satelliteNetworkDirectory, sprintf( ...
                'dynamic_state_%dms_for_%ds', ...
                snapshotIntervalMs, durationSeconds));
            [fstateFiles, snapshotTimesNs] = ...
                ThesisHypatiaStateAnalyzer.findFstateFiles( ...
                dynamicStateDirectory, snapshotIntervalMs, durationSeconds);

            groundStationPairs = nchoosek(0:groundStationCount - 1, 2);
            pairCount = size(groundStationPairs, 1);
            sourceNodes = int32( ...
                satelliteCount + groundStationPairs(:, 1) + 1);
            destinationNodes = int32( ...
                satelliteCount + groundStationPairs(:, 2) + 1);
            destinationColumns = int32(groundStationPairs(:, 2) + 1);

            % Encoding: -1 means unknown, 0 means no route, and a positive
            % value is the MATLAB one-based index of the next node.
            nextHop = -ones(nodeCount, groundStationCount, 'int32');
            previousPathNodes = zeros( ...
                pairCount, nodeCount + 1, 'int32');
            previousPathLengths = zeros(pairCount, 1, 'int32');
            routeChanges = zeros(pairCount, 1);

            snapshotCount = numel(fstateFiles);
            for snapshotIndex = 1:snapshotCount
                updatePath = fullfile( ...
                    fstateFiles(snapshotIndex).folder, ...
                    fstateFiles(snapshotIndex).name);
                updates = ThesisHypatiaStateAnalyzer.readFstateUpdates( ...
                    updatePath, satelliteCount, ...
                    groundStationCount, nodeCount);
                if ~isempty(updates)
                    rowIndices = updates(:, 1) + 1;
                    columnIndices = updates(:, 2) - satelliteCount + 1;
                    encodedNextHops = updates(:, 3) + 1;
                    linearIndices = sub2ind( ...
                        size(nextHop), rowIndices, columnIndices);
                    nextHop(linearIndices) = int32(encodedNextHops);
                end

                if snapshotIndex == 1
                    ThesisHypatiaStateAnalyzer.verifyInitialStateComplete( ...
                        nextHop, satelliteCount, groundStationCount);
                end

                for pairIndex = 1:pairCount
                    currentNode = sourceNodes(pairIndex);
                    destinationNode = destinationNodes(pairIndex);
                    destinationColumn = destinationColumns(pairIndex);
                    oldLength = previousPathLengths(pairIndex);
                    newLength = int32(1);
                    pathChanged = oldLength < 1 || ...
                        previousPathNodes(pairIndex, 1) ~= currentNode;
                    previousPathNodes(pairIndex, 1) = currentNode;

                    firstNextHop = nextHop( ...
                        double(currentNode), double(destinationColumn));
                    if firstNextHop == 0
                        newLength = int32(0);
                        pathChanged = oldLength ~= 0;
                    else
                        while currentNode ~= destinationNode
                            nextNode = nextHop( ...
                                double(currentNode), ...
                                double(destinationColumn));
                            if nextNode < 0
                                error( ...
                                    'ThesisHypatiaStateAnalyzer:IncompleteState', ...
                                    ['No forwarding decision exists for ' ...
                                    'node %d toward ground-station %d at %g ns.'], ...
                                    currentNode - 1, ...
                                    destinationColumn - 1, ...
                                    snapshotTimesNs(snapshotIndex));
                            end
                            if nextNode == 0
                                newLength = int32(0);
                                pathChanged = oldLength ~= 0;
                                break;
                            end

                            newLength = newLength + 1;
                            if newLength > nodeCount + 1
                                error( ...
                                    'ThesisHypatiaStateAnalyzer:ForwardingLoop', ...
                                    ['Forwarding loop detected for pair ' ...
                                    '%d -> %d at %g ns.'], ...
                                    sourceNodes(pairIndex) - 1, ...
                                    destinationNode - 1, ...
                                    snapshotTimesNs(snapshotIndex));
                            end
                            if ~pathChanged && ...
                                    (newLength > oldLength || ...
                                    previousPathNodes( ...
                                    pairIndex, double(newLength)) ~= nextNode)
                                pathChanged = true;
                            end
                            previousPathNodes( ...
                                pairIndex, double(newLength)) = nextNode;
                            currentNode = nextNode;
                        end
                        if ~pathChanged && newLength ~= oldLength
                            pathChanged = true;
                        end
                    end

                    previousPathLengths(pairIndex) = newLength;
                    if snapshotIndex > 1 && pathChanged
                        routeChanges(pairIndex) = ...
                            routeChanges(pairIndex) + 1;
                    end
                end

                if progressInterval > 0 && ...
                        (mod(snapshotIndex, progressInterval) == 0 || ...
                        snapshotIndex == snapshotCount)
                    fprintf( ...
                        'Hypatia fstate analysis: %d / %d snapshots\n', ...
                        snapshotIndex, snapshotCount);
                end
            end

            sortedRouteChanges = sort(routeChanges);
            ecdfProbabilities = ...
                (1:pairCount)' ./ pairCount;
            pairTable = table( ...
                groundStationPairs(:, 1), ...
                groundStationPairs(:, 2), ...
                double(sourceNodes - 1), ...
                double(destinationNodes - 1), ...
                routeChanges, ...
                'VariableNames', { ...
                'SourceGroundStationId', ...
                'DestinationGroundStationId', ...
                'SourceNodeId', ...
                'DestinationNodeId', ...
                'RouteChanges'});

            result = struct( ...
                'SatelliteNetworkDirectory', ...
                satelliteNetworkDirectory, ...
                'SatelliteCount', satelliteCount, ...
                'GroundStationCount', groundStationCount, ...
                'SnapshotIntervalMs', snapshotIntervalMs, ...
                'DurationSeconds', durationSeconds, ...
                'SnapshotCount', snapshotCount, ...
                'PairTable', pairTable, ...
                'SortedRouteChanges', sortedRouteChanges, ...
                'EcdfProbabilities', ecdfProbabilities, ...
                'MedianRouteChanges', median(routeChanges), ...
                'MeanRouteChanges', mean(routeChanges), ...
                'P90RouteChanges', sortedRouteChanges( ...
                ceil(0.90 * pairCount)), ...
                'P95RouteChanges', sortedRouteChanges( ...
                ceil(0.95 * pairCount)), ...
                'FractionAtLeast7RouteChanges', ...
                mean(routeChanges >= 7));
        end

        function comparison = compareRouteChangeEcdf( ...
                result, referenceEcdfPath)
            if ~isstruct(result) || ...
                    ~isfield(result, 'SortedRouteChanges')
                error('ThesisHypatiaStateAnalyzer:InvalidResult', ...
                    'Result must come from analyzeRouteChanges.');
            end
            if ~(ischar(referenceEcdfPath) || ...
                    (isstring(referenceEcdfPath) && ...
                    isscalar(referenceEcdfPath)))
                error('ThesisHypatiaStateAnalyzer:InvalidReferencePath', ...
                    ['Reference ECDF path must be a character vector ' ...
                    'or string scalar.']);
            end
            referenceEcdfPath = char(referenceEcdfPath);
            if ~isfile(referenceEcdfPath)
                error('ThesisHypatiaStateAnalyzer:MissingReferenceEcdf', ...
                    'Reference ECDF file not found: %s', ...
                    referenceEcdfPath);
            end

            referenceData = readmatrix(referenceEcdfPath, ...
                'FileType', 'text', 'Delimiter', ',');
            if size(referenceData, 2) ~= 2 || ...
                    size(referenceData, 1) < 2
                error('ThesisHypatiaStateAnalyzer:MalformedReferenceEcdf', ...
                    'Reference ECDF must have two columns.');
            end
            referenceValues = referenceData( ...
                isfinite(referenceData(:, 1)), 1);
            calculatedValues = double(result.SortedRouteChanges);
            sameCount = numel(referenceValues) == ...
                numel(calculatedValues);
            if sameCount
                differences = calculatedValues - referenceValues;
                mismatchCount = sum(differences ~= 0);
                maximumAbsoluteDifference = ...
                    max(abs(differences), [], 'omitmissing');
            else
                mismatchCount = abs( ...
                    numel(calculatedValues) - numel(referenceValues));
                maximumAbsoluteDifference = Inf;
            end

            comparison = struct( ...
                'MatchesExactly', sameCount && mismatchCount == 0, ...
                'CalculatedPairCount', numel(calculatedValues), ...
                'ReferencePairCount', numel(referenceValues), ...
                'MismatchCount', mismatchCount, ...
                'MaximumAbsoluteDifference', ...
                maximumAbsoluteDifference);
        end
    end

    methods (Static, Access = private)
        function directoryValue = validateDirectoryArgument(directoryValue)
            if ~(ischar(directoryValue) || ...
                    (isstring(directoryValue) && ...
                    isscalar(directoryValue)))
                error( ...
                    'ThesisHypatiaStateAnalyzer:InvalidNetworkDirectory', ...
                    ['Satellite-network directory must be a character ' ...
                    'vector or string scalar.']);
            end
            directoryValue = char(directoryValue);
            if ~isfolder(directoryValue)
                error( ...
                    'ThesisHypatiaStateAnalyzer:MissingNetworkDirectory', ...
                    'Satellite-network directory not found: %s', ...
                    directoryValue);
            end
        end

        function validatePositiveInteger(value, valueName)
            if ~isnumeric(value) || ~isreal(value) || ...
                    ~isscalar(value) || ~isfinite(value) || ...
                    value < 1 || value ~= floor(value)
                error( ...
                    'ThesisHypatiaStateAnalyzer:InvalidPositiveInteger', ...
                    '%s must be a positive integer.', valueName);
            end
        end

        function validateNonnegativeInteger(value, valueName)
            if ~isnumeric(value) || ~isreal(value) || ...
                    ~isscalar(value) || ~isfinite(value) || ...
                    value < 0 || value ~= floor(value)
                error( ...
                    'ThesisHypatiaStateAnalyzer:InvalidNonnegativeInteger', ...
                    '%s must be a nonnegative integer.', valueName);
            end
        end

        function satelliteCount = readSatelliteCount(tlesPath)
            fileId = fopen(tlesPath, 'r');
            if fileId < 0
                error('ThesisHypatiaStateAnalyzer:TlesReadFailed', ...
                    'Could not open TLE file: %s', tlesPath);
            end
            fileCleanup = onCleanup(@() fclose(fileId));
            firstLine = fgetl(fileId);
            values = sscanf(firstLine, '%d %d');
            if numel(values) ~= 2 || any(values < 1)
                error('ThesisHypatiaStateAnalyzer:MalformedTles', ...
                    'The first TLE line must contain two positive counts.');
            end
            satelliteCount = double(prod(values));
            clear fileCleanup;
        end

        function groundStationCount = countGroundStations(pathValue)
            lines = readlines(pathValue);
            lines = lines(strlength(strtrim(lines)) > 0);
            groundStationCount = numel(lines);
            for lineIndex = 1:groundStationCount
                columns = split(lines(lineIndex), ',');
                if numel(columns) ~= 8 || ...
                        str2double(columns(1)) ~= lineIndex - 1
                    error( ...
                        'ThesisHypatiaStateAnalyzer:MalformedGroundStations', ...
                        ['Ground-station rows must have eight columns ' ...
                        'and consecutive zero-based identifiers.']);
                end
            end
        end

        function [files, timesNs] = findFstateFiles( ...
                dynamicStateDirectory, snapshotIntervalMs, ...
                durationSeconds)
            if ~isfolder(dynamicStateDirectory)
                error( ...
                    'ThesisHypatiaStateAnalyzer:MissingDynamicState', ...
                    'Dynamic-state directory not found: %s', ...
                    dynamicStateDirectory);
            end
            files = dir(fullfile( ...
                dynamicStateDirectory, 'fstate_*.txt'));
            if isempty(files)
                error('ThesisHypatiaStateAnalyzer:MissingFstateFiles', ...
                    'No fstate files found in %s.', dynamicStateDirectory);
            end

            timesNs = zeros(numel(files), 1);
            for fileIndex = 1:numel(files)
                token = regexp(files(fileIndex).name, ...
                    '^fstate_(\d+)\.txt$', 'tokens', 'once');
                if isempty(token)
                    error( ...
                        'ThesisHypatiaStateAnalyzer:MalformedFstateName', ...
                        'Invalid fstate filename: %s', ...
                        files(fileIndex).name);
                end
                timesNs(fileIndex) = str2double(token{1});
            end
            [timesNs, order] = sort(timesNs);
            files = files(order);

            intervalNs = snapshotIntervalMs * 1e6;
            expectedTimesNs = ...
                (0:intervalNs:durationSeconds * 1e9 - intervalNs)';
            if ~isequal(timesNs, expectedTimesNs)
                error( ...
                    'ThesisHypatiaStateAnalyzer:IncompleteTimeSeries', ...
                    ['Fstate files must cover every requested snapshot ' ...
                    'exactly once.']);
            end
        end

        function updates = readFstateUpdates( ...
                pathValue, satelliteCount, ...
                groundStationCount, nodeCount)
            fileInformation = dir(pathValue);
            if fileInformation.bytes == 0
                updates = zeros(0, 3);
                return;
            end
            rawData = readmatrix(pathValue, ...
                'FileType', 'text', 'Delimiter', ',');
            if ~isnumeric(rawData) || size(rawData, 2) ~= 5 || ...
                    any(~isfinite(rawData), 'all') || ...
                    any(rawData ~= floor(rawData), 'all')
                error('ThesisHypatiaStateAnalyzer:MalformedFstate', ...
                    'Fstate rows must contain five finite integers: %s', ...
                    pathValue);
            end

            updates = rawData(:, 1:3);
            currentNodes = updates(:, 1);
            destinationNodes = updates(:, 2);
            nextNodes = updates(:, 3);
            if any(currentNodes < 0 | currentNodes >= nodeCount) || ...
                    any(destinationNodes < satelliteCount | ...
                    destinationNodes >= nodeCount) || ...
                    any(nextNodes < -1 | nextNodes >= nodeCount)
                error('ThesisHypatiaStateAnalyzer:InvalidFstateNode', ...
                    'Fstate contains a node outside the valid range: %s', ...
                    pathValue);
            end
            if numel(unique(destinationNodes)) > groundStationCount
                error('ThesisHypatiaStateAnalyzer:InvalidFstateNode', ...
                    'Fstate contains too many destination ground stations.');
            end
        end

        function verifyInitialStateComplete( ...
                nextHop, satelliteCount, groundStationCount)
            unknownEntries = nextHop < 0;
            permittedUnknown = false(size(nextHop));
            for groundStationIndex = 1:groundStationCount
                destinationNode = ...
                    satelliteCount + groundStationIndex;
                permittedUnknown( ...
                    destinationNode, groundStationIndex) = true;
            end
            if any(unknownEntries & ~permittedUnknown, 'all')
                error( ...
                    'ThesisHypatiaStateAnalyzer:IncompleteInitialState', ...
                    ['The first fstate file does not initialize all ' ...
                    'required forwarding decisions.']);
            end
        end
    end
end
