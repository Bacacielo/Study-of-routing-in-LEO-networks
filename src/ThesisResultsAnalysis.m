        function setErrorbarYLimits(lowerValues, upperValues, clampLowerAtZero)
            if nargin < 3
                clampLowerAtZero = false;
            end
            if clampLowerAtZero
                lowerLimit = 0;
            else
                lowerLimit = min([0, lowerValues(:)']);
            end
            upperLimit = max([0, upperValues(:)']);
            span = upperLimit - lowerLimit;
            if span <= 0
                span = 1;
            end
            padding = 0.08 * span;
            if clampLowerAtZero
                ylim([0, upperLimit + padding]);
            else
                ylim([lowerLimit - padding, upperLimit + padding]);
            end
        end
