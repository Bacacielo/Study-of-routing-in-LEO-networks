classdef ThesisResultsAnalysis
    methods (Static)
        function summary = summarize(results)
            ThesisResultsAnalysis.validateResultsTable(results);

            [bestImprovement, bestIdx] = max(results.EffectiveLatencyImprovementMs);
            [worstImprovement, worstIdx] = min(results.EffectiveLatencyImprovementMs);
            [maxAvailabilityGain, availabilityIdx] = max(results.ReliableAvailabilityGain);

            summary = struct();
            summary.RowCount = height(results);
            summary.MeanAvailabilityGain = mean(results.ReliableAvailabilityGain);
            summary.MeanReliableLatencyPenaltyMs = mean(results.ReliableLatencyPenaltyMs);
            summary.MeanEffectiveLatencyImprovementMs = mean(results.EffectiveLatencyImprovementMs);
            summary.PositiveEffectiveLatencyImprovementRate = mean(results.EffectiveLatencyImprovementMs > 0);
            summary.AvailabilityGainStatistics = ThesisResultsAnalysis.descriptiveStatistics( ...
                results.ReliableAvailabilityGain);
            summary.LatencyPenaltyStatistics = ThesisResultsAnalysis.descriptiveStatistics( ...
                results.ReliableLatencyPenaltyMs);
            summary.EffectiveLatencyImprovementStatistics = ThesisResultsAnalysis.descriptiveStatistics( ...
                results.EffectiveLatencyImprovementMs);
            summary.EffectiveLatencyOutcomeCounts = struct( ...
                'Positive', sum(results.EffectiveLatencyImprovementMs > 0), ...
                'Zero', sum(results.EffectiveLatencyImprovementMs == 0), ...
                'Negative', sum(results.EffectiveLatencyImprovementMs < 0));
            summary.LatencyPenaltyImprovementCorrelation = ThesisResultsAnalysis.pearsonCorrelation( ...
                results.ReliableLatencyPenaltyMs, results.EffectiveLatencyImprovementMs);
            nonzeroTradeoff = results.ReliableLatencyPenaltyMs ~= 0 | ...
                results.EffectiveLatencyImprovementMs ~= 0;
            summary.NonzeroTradeoffCaseCount = sum(nonzeroTradeoff);
            if summary.NonzeroTradeoffCaseCount >= 2
                summary.LatencyPenaltyImprovementCorrelationNonzero = ...
                    ThesisResultsAnalysis.pearsonCorrelation( ...
                    results.ReliableLatencyPenaltyMs(nonzeroTradeoff), ...
                    results.EffectiveLatencyImprovementMs(nonzeroTradeoff));
            else
                summary.LatencyPenaltyImprovementCorrelationNonzero = NaN;
            end
            summary.BestEffectiveLatencyImprovementMs = bestImprovement;
            summary.BestEffectiveLatencyCase = results(bestIdx, :);
            summary.WorstEffectiveLatencyImprovementMs = worstImprovement;
            summary.WorstEffectiveLatencyCase = results(worstIdx, :);
            summary.MaxAvailabilityGain = maxAvailabilityGain;
            summary.MaxAvailabilityGainCase = results(availabilityIdx, :);
            summary.NegativeEffectiveLatencyCaseCount = sum(results.EffectiveLatencyImprovementMs < 0);
            summary.SensitivityByReliabilityWeight = ThesisResultsAnalysis.groupMetricMeans(results, 'ReliabilityWeight');
            summary.SensitivityByShortcutRisk = ThesisResultsAnalysis.groupMetricMeans(results, 'ShortcutRiskAvailability');
            summary.SensitivityByContactDutyCycle = ThesisResultsAnalysis.groupMetricMeans(results, 'ContactDutyCycle');
            summary.SensitivityByConstellation = ThesisResultsAnalysis.groupByConstellation(results);
            summary.RouteChangeStatistics = ThesisResultsAnalysis.routeChangeStatistics(results);
        end

        function summary = summarizeRobustness(mainResults, seedResults, routePairResults)
            ThesisResultsAnalysis.validateResultsTable(mainResults);
            ThesisResultsAnalysis.validateResultsTable(seedResults);
            ThesisResultsAnalysis.validateResultsTable(routePairResults);
            ThesisResultsAnalysis.requireVariables(seedResults, {'Seed'});
            ThesisResultsAnalysis.requireVariables(routePairResults, {'SourceNode', 'DestinationNode'});

            summary = struct();
            summary.MainEffectiveLatency = ThesisResultsAnalysis.descriptiveStatistics( ...
                mainResults.EffectiveLatencyImprovementMs);
            summary.SeedEffectiveLatency = ThesisResultsAnalysis.descriptiveStatistics( ...
                seedResults.EffectiveLatencyImprovementMs);
            summary.RoutePairEffectiveLatency = ThesisResultsAnalysis.descriptiveStatistics( ...
                routePairResults.EffectiveLatencyImprovementMs);
            summary.BySeed = ThesisResultsAnalysis.groupRobustnessMetrics(seedResults, {'Seed'});
            summary.ByRoutePair = ThesisResultsAnalysis.groupRobustnessMetrics( ...
                routePairResults, {'SourceNode', 'DestinationNode'});
        end

        function summary = summarizeTimeHorizon(results)
            ThesisResultsAnalysis.validateResultsTable(results);
            ThesisResultsAnalysis.requireVariables(results, {'TimeSteps'});
            if ~isnumeric(results.TimeSteps) || any(~isfinite(results.TimeSteps)) || ...
                    any(results.TimeSteps < 2) || any(results.TimeSteps ~= floor(results.TimeSteps))
                error('ThesisResultsAnalysis:InvalidTimeHorizon', ...
                    'Time-horizon results require integer TimeSteps values of at least 2.');
            end

            workingResults = results;
            transitionCounts = workingResults.TimeSteps - 1;
            workingResults.PositiveEffectiveLatencyIndicator = double( ...
                workingResults.EffectiveLatencyImprovementMs > 0);
            workingResults.BaselineRouteChangeRate = ...
                workingResults.BaselineRouteChanges ./ transitionCounts;
            workingResults.ReliableRouteChangeRate = ...
                workingResults.ReliableRouteChanges ./ transitionCounts;
            workingResults.RouteChangeRateDelta = ...
                workingResults.ReliableRouteChangeRate - ...
                workingResults.BaselineRouteChangeRate;

            byTimeSteps = groupsummary(workingResults, 'TimeSteps', {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'PositiveEffectiveLatencyIndicator', ...
                'BaselineRouteChangeRate', ...
                'ReliableRouteChangeRate', ...
                'RouteChangeRateDelta'});

            summary = struct();
            summary.RowCount = height(results);
            summary.ByTimeSteps = byTimeSteps;
            summary.MeanAvailabilityGainPositiveAtAllHorizons = ...
                all(byTimeSteps.mean_ReliableAvailabilityGain > 0);
            summary.MeanEffectiveLatencyImprovementPositiveAtAllHorizons = ...
                all(byTimeSteps.mean_EffectiveLatencyImprovementMs > 0);
            summary.LongestTimeHorizon = max(byTimeSteps.TimeSteps);
        end

        function summary = summarizeControlledConstellation(results)
            ThesisResultsAnalysis.validateResultsTable(results);
            ThesisResultsAnalysis.requireVariables(results, ...
                {'SourceNode', 'DestinationNode'});

            workingResults = results;
            workingResults.RouteChangeDelta = ...
                workingResults.ReliableRouteChanges - workingResults.BaselineRouteChanges;
            byConstellation = groupsummary(workingResults, ...
                {'PlaneCount', 'SatellitesPerPlane', 'NodeCount', ...
                'SourceNode', 'DestinationNode'}, {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'RouteChangeDelta'});

            summary = struct();
            summary.RowCount = height(results);
            summary.ByConstellation = byConstellation;
        end

        function summary = summarizeTopologyOnlyAblation(results)
            requiredVariables = { ...
                'ContactDutyCycle', ...
                'BaselineRouteChangeRate', ...
                'ReliableRouteChangeRate'};
            ThesisResultsAnalysis.requireVariables(results, requiredVariables);
            if height(results) == 0 || any(~isfinite(results.ContactDutyCycle)) || ...
                    any(~isfinite(results.BaselineRouteChangeRate)) || ...
                    any(~isfinite(results.ReliableRouteChangeRate))
                error('ThesisResultsAnalysis:InvalidTopologyOnlyAblation', ...
                    'Topology-only ablation results must be nonempty and finite.');
            end

            byDutyCycle = groupsummary(results, 'ContactDutyCycle', {'mean', 'std'}, { ...
                'BaselineRouteChangeRate', 'ReliableRouteChangeRate'});
            dynamicRows = byDutyCycle.ContactDutyCycle < 1;
            staticRows = byDutyCycle.ContactDutyCycle == 1;

            summary = struct();
            summary.RowCount = height(results);
            summary.ByContactDutyCycle = byDutyCycle;
            summary.DynamicContactProducesRouteChanges = ...
                any(byDutyCycle.mean_BaselineRouteChangeRate(dynamicRows) > 0) && ...
                any(byDutyCycle.mean_ReliableRouteChangeRate(dynamicRows) > 0);
            summary.StaticControlHasNoRouteChanges = ...
                any(staticRows) && ...
                all(byDutyCycle.mean_BaselineRouteChangeRate(staticRows) == 0) && ...
                all(byDutyCycle.mean_ReliableRouteChangeRate(staticRows) == 0);
        end

        function summary = summarizeReliabilityStressAblation(results)
            requiredVariables = { ...
                'StressEnabled', ...
                'ShortcutRiskAvailability', ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'SnapshotCount', ...
                'BaselineRiskyPathSnapshotCount', ...
                'BaselineRiskyPathRate', ...
                'ReliableRiskyPathSnapshotCount', ...
                'ReliableRiskyPathRate', ...
                'PathDifferenceRate', ...
                'MeanEffectiveImprovementWhenBaselineRiskyMs', ...
                'MeanEffectiveImprovementWhenBaselineNotRiskyMs'};
            ThesisResultsAnalysis.requireVariables(results, requiredVariables);
            stressEnabled = results.StressEnabled;
            validStressIndicator = (islogical(stressEnabled) || ...
                isnumeric(stressEnabled)) && ...
                all(ismember(stressEnabled, [false true]));
            if height(results) == 0 || ~validStressIndicator || ...
                    any(~isfinite(results.ReliableAvailabilityGain)) || ...
                    any(~isfinite(results.ReliableLatencyPenaltyMs)) || ...
                    any(~isfinite(results.EffectiveLatencyImprovementMs)) || ...
                    any(~isfinite(results.SnapshotCount)) || ...
                    any(results.SnapshotCount < 1)
                error('ThesisResultsAnalysis:InvalidReliabilityStressAblation', ...
                    'Reliability-stress ablation results must be nonempty and finite.');
            end

            stressMask = logical(stressEnabled);
            stressedResults = results(stressMask, :);
            controlResults = results(~stressMask, :);
            if height(stressedResults) == 0 || height(controlResults) == 0 || ...
                    any(~isfinite(stressedResults.ShortcutRiskAvailability))
                error('ThesisResultsAnalysis:IncompleteReliabilityStressAblation', ...
                    'Both finite stressed rows and no-stress control rows are required.');
            end

            byRisk = groupsummary(stressedResults, ...
                'ShortcutRiskAvailability', {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'PathDifferenceRate', ...
                'BaselineRiskyPathRate', ...
                'ReliableRiskyPathRate'});
            byRisk = sortrows(byRisk, 'ShortcutRiskAvailability');

            summary = struct();
            summary.RowCount = height(results);
            summary.StressRowCount = height(stressedResults);
            summary.NoStressRowCount = height(controlResults);
            summary.ByShortcutRiskAvailability = byRisk;
            summary.NoStressAvailabilityGain = ...
                ThesisResultsAnalysis.descriptiveStatistics( ...
                controlResults.ReliableAvailabilityGain);
            summary.NoStressLatencyPenalty = ...
                ThesisResultsAnalysis.descriptiveStatistics( ...
                controlResults.ReliableLatencyPenaltyMs);
            summary.NoStressEffectiveLatencyImprovement = ...
                ThesisResultsAnalysis.descriptiveStatistics( ...
                controlResults.EffectiveLatencyImprovementMs);
            summary.NoStressOutcomeCounts = struct( ...
                'Positive', sum(controlResults.EffectiveLatencyImprovementMs > 0), ...
                'Zero', sum(controlResults.EffectiveLatencyImprovementMs == 0), ...
                'Negative', sum(controlResults.EffectiveLatencyImprovementMs < 0));

            totalStressSnapshots = sum(stressedResults.SnapshotCount);
            baselineRiskySnapshots = ...
                sum(stressedResults.BaselineRiskyPathSnapshotCount);
            reliableRiskySnapshots = ...
                sum(stressedResults.ReliableRiskyPathSnapshotCount);
            baselineNonRiskySnapshots = totalStressSnapshots - baselineRiskySnapshots;
            riskyRows = stressedResults.BaselineRiskyPathSnapshotCount > 0;
            nonRiskyCounts = stressedResults.SnapshotCount - ...
                stressedResults.BaselineRiskyPathSnapshotCount;
            nonRiskyRows = nonRiskyCounts > 0;
            riskyConditionalMean = NaN;
            if baselineRiskySnapshots > 0
                riskyMeans = ...
                    stressedResults.MeanEffectiveImprovementWhenBaselineRiskyMs;
                riskyConditionalMean = ...
                    sum(riskyMeans(riskyRows) .* ...
                    stressedResults.BaselineRiskyPathSnapshotCount(riskyRows)) / ...
                    baselineRiskySnapshots;
            end
            nonRiskyConditionalMean = NaN;
            if baselineNonRiskySnapshots > 0
                nonRiskyMeans = ...
                    stressedResults.MeanEffectiveImprovementWhenBaselineNotRiskyMs;
                nonRiskyConditionalMean = ...
                    sum(nonRiskyMeans(nonRiskyRows) .* ...
                    nonRiskyCounts(nonRiskyRows)) / baselineNonRiskySnapshots;
            end

            summary.SnapshotDiagnostics = struct( ...
                'TotalStressSnapshots', totalStressSnapshots, ...
                'BaselineRiskySnapshots', baselineRiskySnapshots, ...
                'BaselineRiskySnapshotRate', ...
                    baselineRiskySnapshots / totalStressSnapshots, ...
                'ReliableRiskySnapshots', reliableRiskySnapshots, ...
                'ReliableRiskySnapshotRate', ...
                    reliableRiskySnapshots / totalStressSnapshots, ...
                'MeanImprovementWhenBaselineRiskyMs', ...
                    riskyConditionalMean, ...
                'MeanImprovementWhenBaselineNotRiskyMs', ...
                    nonRiskyConditionalMean);

            riskValues = byRisk.ShortcutRiskAvailability;
            meanImprovements = byRisk.mean_EffectiveLatencyImprovementMs;
            reversalIndex = find( ...
                meanImprovements(1:end - 1) > 0 & ...
                meanImprovements(2:end) <= 0, 1, 'first');
            summary.ObservedSignReversal = ~isempty(reversalIndex);
            summary.SignReversalLowerAvailability = NaN;
            summary.SignReversalUpperAvailability = NaN;
            summary.InterpolatedZeroCrossingAvailability = NaN;
            if summary.ObservedSignReversal
                lowerX = riskValues(reversalIndex);
                upperX = riskValues(reversalIndex + 1);
                lowerY = meanImprovements(reversalIndex);
                upperY = meanImprovements(reversalIndex + 1);
                summary.SignReversalLowerAvailability = lowerX;
                summary.SignReversalUpperAvailability = upperX;
                summary.InterpolatedZeroCrossingAvailability = ...
                    lowerX + (0 - lowerY) * (upperX - lowerX) / ...
                    (upperY - lowerY);
            end
        end

        function figurePaths = writeFigures(results, outputDir)
            ThesisResultsAnalysis.validateResultsTable(results);
            if ~isfolder(outputDir)
                mkdir(outputDir);
            end

            figurePaths = struct();
            figurePaths.ReliabilityWeightSensitivity = fullfile(outputDir, 'reliability_weight_sensitivity.png');
            figurePaths.EffectiveLatencyByRisk = fullfile(outputDir, 'effective_latency_improvement_by_risk.png');
            figurePaths.LatencyTradeoff = fullfile(outputDir, 'latency_tradeoff.png');
            figurePaths.RouteChangesComparison = fullfile(outputDir, 'route_changes_comparison.png');

            weightSummary = summaryToPlotTable(ThesisResultsAnalysis.groupMetricMeans(results, 'ReliabilityWeight'), 'ReliabilityWeight');
            f = figure('Visible', 'off');
            subplot(3, 1, 1);
            errorbar(weightSummary.Key, weightSummary.AvailabilityGain, weightSummary.AvailabilityGainStd, '-o', 'LineWidth', 1.5);
            grid on;
            xlim([min(weightSummary.Key) - 0.05, max(weightSummary.Key) + 0.05]);
            ylabel('Availability gain');
            title('Reliability-weight sensitivity (mean +/- std)');
            subplot(3, 1, 2);
            errorbar(weightSummary.Key, weightSummary.LatencyPenaltyMs, weightSummary.LatencyPenaltyMsStd, '-o', 'LineWidth', 1.5);
            grid on;
            xlim([min(weightSummary.Key) - 0.05, max(weightSummary.Key) + 0.05]);
            ylabel('Latency penalty (ms)');
            subplot(3, 1, 3);
            errorbar(weightSummary.Key, weightSummary.EffectiveLatencyImprovementMs, weightSummary.EffectiveLatencyImprovementMsStd, '-o', 'LineWidth', 1.5);
            grid on;
            xlim([min(weightSummary.Key) - 0.05, max(weightSummary.Key) + 0.05]);
            xlabel('Reliability weight');
            ylabel('Effective latency improvement (ms)');
            ThesisResultsAnalysis.saveAndClose(f, figurePaths.ReliabilityWeightSensitivity);

            riskSummary = ThesisResultsAnalysis.groupMeanStd(results.ShortcutRiskAvailability, results.EffectiveLatencyImprovementMs);
            f = figure('Visible', 'off');
            errorbar(riskSummary.Key, riskSummary.MeanValue, riskSummary.StdValue, '-o', 'LineWidth', 1.5);
            grid on;
            xlim([min(riskSummary.Key) - 0.02, max(riskSummary.Key) + 0.02]);
            xlabel('Shortcut-link availability');
            ylabel('Effective latency improvement (ms)');
            title('Effective latency improvement by shortcut-link availability (mean +/- std)');
            ThesisResultsAnalysis.saveAndClose(f, figurePaths.EffectiveLatencyByRisk);

            f = figure('Visible', 'off');
            scatter(results.ReliableLatencyPenaltyMs, results.EffectiveLatencyImprovementMs, ...
                42, results.ReliabilityWeight, 'filled', ...
                'MarkerFaceAlpha', 0.78, ...
                'MarkerEdgeColor', [0.20 0.20 0.20], ...
                'LineWidth', 0.35);
            hold on;
            xline(0, ':', 'Color', [0.35 0.35 0.35], 'LineWidth', 1);
            yline(0, ':', 'Color', [0.35 0.35 0.35], 'LineWidth', 1);
            hold off;
            grid on;
            xDataRange = max(results.ReliableLatencyPenaltyMs) - min(results.ReliableLatencyPenaltyMs);
            yDataRange = max(results.EffectiveLatencyImprovementMs) - min(results.EffectiveLatencyImprovementMs);
            xPadding = max(xDataRange * 0.04, 0.15);
            yPadding = max(yDataRange * 0.06, 0.50);
            xlim([min(results.ReliableLatencyPenaltyMs) - xPadding, max(results.ReliableLatencyPenaltyMs) + xPadding]);
            ylim([min(results.EffectiveLatencyImprovementMs) - yPadding, max(results.EffectiveLatencyImprovementMs) + yPadding]);
            cb = colorbar;
            ylabel(cb, 'Reliability weight');
            xlabel('Reliable latency penalty (ms)');
            ylabel('Effective latency improvement (ms)');
            title('Latency penalty versus effective latency improvement');
            ThesisResultsAnalysis.saveAndClose(f, figurePaths.LatencyTradeoff);

            f = figure('Visible', 'off');
            routeChangeMeans = [mean(results.BaselineRouteChanges), mean(results.ReliableRouteChanges)];
            routeChangeStds = [std(results.BaselineRouteChanges), std(results.ReliableRouteChanges)];
            bar(routeChangeMeans);
            hold on;
            errorbar(1:numel(routeChangeMeans), routeChangeMeans, routeChangeStds, 'k', 'LineStyle', 'none', 'LineWidth', 1);
            hold off;
            grid on;
            set(gca, 'XTickLabel', {'Latency-only', 'Reliability-aware'});
            ylabel('Route changes');
            title('Route changes by routing policy (mean +/- std)');
            ThesisResultsAnalysis.setErrorbarYLimits(routeChangeMeans - routeChangeStds, routeChangeMeans + routeChangeStds, true);
            ThesisResultsAnalysis.saveAndClose(f, figurePaths.RouteChangesComparison);
        end

        function robustnessFigurePath = writeRobustnessFigure(mainResults, seedResults, routePairResults, outputDir)
            ThesisResultsAnalysis.validateResultsTable(mainResults);
            ThesisResultsAnalysis.validateResultsTable(seedResults);
            ThesisResultsAnalysis.validateResultsTable(routePairResults);
            if ~isfolder(outputDir)
                mkdir(outputDir);
            end

            robustnessFigurePath = fullfile(outputDir, 'robustness_effective_latency_summary.png');
            meanImprovements = [ ...
                mean(mainResults.EffectiveLatencyImprovementMs), ...
                mean(seedResults.EffectiveLatencyImprovementMs), ...
                mean(routePairResults.EffectiveLatencyImprovementMs)];
            stdImprovements = [ ...
                std(mainResults.EffectiveLatencyImprovementMs), ...
                std(seedResults.EffectiveLatencyImprovementMs), ...
                std(routePairResults.EffectiveLatencyImprovementMs)];

            f = figure('Visible', 'off');
            bar(meanImprovements);
            hold on;
            errorbar(1:numel(meanImprovements), meanImprovements, stdImprovements, 'k', 'LineStyle', 'none', 'LineWidth', 1);
            hold off;
            grid on;
            set(gca, 'XTickLabel', {'Main', 'Seed robustness', 'Pair robustness'});
            ylabel('Effective latency improvement (ms)');
            title('Effective-latency improvement across robustness checks (mean +/- std)');
            ThesisResultsAnalysis.setErrorbarYLimits(meanImprovements - stdImprovements, meanImprovements + stdImprovements, false);
            ThesisResultsAnalysis.saveAndClose(f, robustnessFigurePath);
        end

        function outputPath = writeReliabilityStressAblationFigure(results, outputDir)
            summary = ThesisResultsAnalysis.summarizeReliabilityStressAblation(results);
            if ~isfolder(outputDir)
                mkdir(outputDir);
            end
            outputPath = fullfile(outputDir, 'reliability_stress_ablation.png');

            grouped = summary.ByShortcutRiskAvailability;
            riskValues = grouped.ShortcutRiskAvailability;
            meanImprovement = grouped.mean_EffectiveLatencyImprovementMs;
            stdImprovement = grouped.std_EffectiveLatencyImprovementMs;

            f = figure('Visible', 'off');
            layout = tiledlayout(f, 2, 1, 'TileSpacing', 'compact', ...
                'Padding', 'compact');

            nexttile(layout);
            errorbar(riskValues, meanImprovement, stdImprovement, ...
                '-o', 'LineWidth', 1.5, 'MarkerFaceColor', [0.15 0.45 0.75]);
            hold on;
            yline(0, ':k', 'LineWidth', 1.1);
            if summary.ObservedSignReversal
                xline(summary.InterpolatedZeroCrossingAvailability, '--', ...
                    'Color', [0.75 0.25 0.20], 'LineWidth', 1.1);
            end
            hold off;
            grid on;
            xlim([min(riskValues) - 0.03, max(riskValues) + 0.03]);
            ylabel('Effective improvement (ms)');
            title('Reliability-stress ablation (mean +/- std)');
            ThesisResultsAnalysis.setErrorbarYLimits( ...
                meanImprovement - stdImprovement, ...
                meanImprovement + stdImprovement, false);

            nexttile(layout);
            plot(riskValues, ...
                100 * grouped.mean_BaselineRiskyPathRate, ...
                '-o', 'LineWidth', 1.5, 'MarkerFaceColor', [0.20 0.55 0.25]);
            hold on;
            plot(riskValues, ...
                100 * grouped.mean_ReliableRiskyPathRate, ...
                '-s', 'LineWidth', 1.5, 'MarkerFaceColor', [0.80 0.45 0.15]);
            hold off;
            grid on;
            xlim([min(riskValues) - 0.03, max(riskValues) + 0.03]);
            ylim([0, max(5, 1.15 * max(100 * [ ...
                grouped.mean_BaselineRiskyPathRate; ...
                grouped.mean_ReliableRiskyPathRate]))]);
            xlabel('Risky shortcut availability');
            ylabel('Risky-path snapshots (%)');
            legend({'Latency-only', 'Reliability-aware'}, ...
                'Location', 'best');

            ThesisResultsAnalysis.saveAndClose(f, outputPath);
        end

        function writeNotes(summary, outputPath, robustnessSummary, timeHorizonSummary, ...
                controlledConstellationAnalysis, topologyOnlyAblationAnalysis, ...
                reliabilityStressAblationAnalysis)
            if nargin < 3
                robustnessSummary = [];
            end
            if nargin < 4
                timeHorizonSummary = [];
            end
            if nargin < 5
                controlledConstellationAnalysis = [];
            end
            if nargin < 6
                topologyOnlyAblationAnalysis = [];
            end
            if nargin < 7
                reliabilityStressAblationAnalysis = [];
            end
            outputDir = fileparts(outputPath);
            if ~isempty(outputDir) && ~isfolder(outputDir)
                mkdir(outputDir);
            end

            fid = fopen(outputPath, 'w');
            assert(fid > 0, 'Unable to open results notes for writing.');
            cleanup = onCleanup(@() fclose(fid));

            best = summary.BestEffectiveLatencyCase;
            availability = summary.MaxAvailabilityGainCase;
            worst = summary.WorstEffectiveLatencyCase;

            fprintf(fid, '# Results Notes\n\n');
            fprintf(fid, '## Core Claim\n\n');
            fprintf(fid, 'Reliability-aware routing trades a small latency penalty for higher route availability. ');
            fprintf(fid, 'The availability gain can reduce availability-adjusted effective latency when risky shortcuts are present.\n\n');

            fprintf(fid, '## Current Experiment Summary\n\n');
            fprintf(fid, '- Rows analyzed: %d\n', summary.RowCount);
            fprintf(fid, '- Mean availability gain: %.4f\n', summary.MeanAvailabilityGain);
            fprintf(fid, '- Mean raw latency penalty: %.4f ms\n', summary.MeanReliableLatencyPenaltyMs);
            fprintf(fid, '- Mean effective latency improvement: %.4f ms\n', summary.MeanEffectiveLatencyImprovementMs);
            fprintf(fid, '- Positive effective-latency improvement rate: %.1f%%\n', 100 * summary.PositiveEffectiveLatencyImprovementRate);
            fprintf(fid, '- Effective-latency outcomes: %d positive, %d zero, %d negative.\n', ...
                summary.EffectiveLatencyOutcomeCounts.Positive, ...
                summary.EffectiveLatencyOutcomeCounts.Zero, ...
                summary.EffectiveLatencyOutcomeCounts.Negative);
            fprintf(fid, '- Best effective-latency improvement: %.4f ms at %d planes, %d satellites per plane, duty cycle %.2f, shortcut-link availability %.2f, reliability weight %.2f.\n', ...
                summary.BestEffectiveLatencyImprovementMs, ...
                best.PlaneCount, ...
                best.SatellitesPerPlane, ...
                best.ContactDutyCycle, ...
                best.ShortcutRiskAvailability, ...
                best.ReliabilityWeight);
            fprintf(fid, '- Maximum availability gain: %.4f at reliability weight %.2f and shortcut-link availability %.2f.\n', ...
                summary.MaxAvailabilityGain, ...
                availability.ReliabilityWeight, ...
                availability.ShortcutRiskAvailability);
            fprintf(fid, '- Worst effective-latency improvement: %.4f ms at reliability weight %.2f and shortcut-link availability %.2f.\n\n', ...
                summary.WorstEffectiveLatencyImprovementMs, ...
                worst.ReliabilityWeight, ...
                worst.ShortcutRiskAvailability);

            fprintf(fid, '## Descriptive Statistics\n\n');
            fprintf(fid, '| Metric | cases | mean | std | observed range |\n');
            fprintf(fid, '|---|---:|---:|---:|---:|\n');
            ThesisResultsAnalysis.writeStatisticsRow(fid, 'Availability gain', summary.AvailabilityGainStatistics);
            ThesisResultsAnalysis.writeStatisticsRow(fid, 'Raw latency penalty (ms)', summary.LatencyPenaltyStatistics);
            ThesisResultsAnalysis.writeStatisticsRow(fid, 'Effective-latency improvement (ms)', summary.EffectiveLatencyImprovementStatistics);
            fprintf(fid, '\n- Pearson correlation over all design cells: %.4f.\n', ...
                summary.LatencyPenaltyImprovementCorrelation);
            fprintf(fid, '- Pearson correlation after excluding zero-tradeoff ties (%d cells): %.4f.\n\n', ...
                summary.NonzeroTradeoffCaseCount, ...
                summary.LatencyPenaltyImprovementCorrelationNonzero);

            fprintf(fid, '## Thesis Claims\n\n');
            fprintf(fid, '- Reliability-aware routing improves mean route availability, but the improvement is modest on average and must be interpreted as a tradeoff.\n');
            fprintf(fid, '- The largest effective-latency gains occur when the latency-only baseline is attracted to low-availability shortcut links.\n');
            fprintf(fid, '- Increasing the reliability weight improves availability slightly, but it can reduce effective-latency improvement because the route may pay too much raw latency.\n');
            fprintf(fid, '- Negative effective-latency improvement appears in %d of %d cases, so the method should be presented as scenario-dependent rather than universally dominant.\n\n', ...
                summary.NegativeEffectiveLatencyCaseCount, ...
                summary.RowCount);

            fprintf(fid, '## Parameter Sensitivity\n\n');
            fprintf(fid, '### Reliability weight\n\n');
            ThesisResultsAnalysis.writeSensitivityTable(fid, summary.SensitivityByReliabilityWeight, 'ReliabilityWeight');
            fprintf(fid, '\n### Shortcut-link availability\n\n');
            ThesisResultsAnalysis.writeSensitivityTable(fid, summary.SensitivityByShortcutRisk, 'ShortcutRiskAvailability');
            fprintf(fid, '\n### Contact duty cycle\n\n');
            ThesisResultsAnalysis.writeSensitivityTable(fid, summary.SensitivityByContactDutyCycle, 'ContactDutyCycle');
            fprintf(fid, '\n### Constellation size\n\n');
            ThesisResultsAnalysis.writeConstellationSensitivityTable( ...
                fid, summary.SensitivityByConstellation);
            fprintf(fid, '\n');

            fprintf(fid, '## Route Stability\n\n');
            ThesisResultsAnalysis.writeRouteChangeStatistics(fid, summary.RouteChangeStatistics);
            fprintf(fid, '\n');

            if ~isempty(robustnessSummary)
                fprintf(fid, '## Robustness Summary\n\n');
                ThesisResultsAnalysis.writeRobustnessStatistics(fid, robustnessSummary);
                fprintf(fid, '\n');
            end

            if ~isempty(timeHorizonSummary)
                fprintf(fid, '## Time-Horizon Sensitivity\n\n');
                ThesisResultsAnalysis.writeTimeHorizonStatistics(fid, timeHorizonSummary);
                fprintf(fid, '\n');
            end

            if ~isempty(controlledConstellationAnalysis)
                fprintf(fid, '## Controlled Constellation-Size Sensitivity\n\n');
                ThesisResultsAnalysis.writeControlledConstellationStatistics( ...
                    fid, controlledConstellationAnalysis);
                fprintf(fid, '\n');
            end

            if ~isempty(topologyOnlyAblationAnalysis)
                fprintf(fid, '## Topology-Only Route-Variability Ablation\n\n');
                ThesisResultsAnalysis.writeTopologyOnlyAblationStatistics( ...
                    fid, topologyOnlyAblationAnalysis);
                fprintf(fid, '\n');
            end

            if ~isempty(reliabilityStressAblationAnalysis)
                fprintf(fid, '## Reliability-Stress Ablation\n\n');
                ThesisResultsAnalysis.writeReliabilityStressAblationStatistics( ...
                    fid, reliabilityStressAblationAnalysis);
                fprintf(fid, '\n');
            end

            fprintf(fid, '## Interpretation\n\n');
            fprintf(fid, '- Shortest-path routing is a latency baseline, but it can select low-availability routes.\n');
            fprintf(fid, '- Reliability-aware routing is useful when low-availability shortcuts distort the latency-only path choice.\n');
            fprintf(fid, '- Effective latency is the thesis-facing comparison metric because it penalizes unreliable routes without claiming a full physical-layer ARQ model.\n');
            fprintf(fid, '- Raw latency penalty should be reported alongside availability gain, otherwise the result is incomplete.\n\n');

            fprintf(fid, '## Scope note\n\n');
            fprintf(fid, 'These results support a graph-level LEO routing study. They do not reproduce Wang et al. stochastic geometry, coverage probability, or exact ARQ delay derivations.\n');
        end
    end

    methods (Static, Access = private)
        function validateResultsTable(results)
            requiredVariables = { ...
                'PlaneCount', ...
                'SatellitesPerPlane', ...
                'ContactDutyCycle', ...
                'ShortcutRiskAvailability', ...
                'ReliabilityWeight', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'ReliableAvailabilityGain', ...
                'BaselineRouteChanges', ...
                'ReliableRouteChanges'};
            missingVariables = setdiff(requiredVariables, results.Properties.VariableNames);
            assert(isempty(missingVariables), 'Results table is missing required analysis variables.');
            assert(height(results) > 0, 'Results table must not be empty.');
        end

        function requireVariables(results, requiredVariables)
            missingVariables = setdiff(requiredVariables, results.Properties.VariableNames);
            assert(isempty(missingVariables), 'Results table is missing required grouping variables.');
        end

        function statistics = descriptiveStatistics(values)
            values = values(:);
            if isempty(values) || ~isnumeric(values) || any(~isfinite(values))
                error('ThesisResultsAnalysis:InvalidMetricValues', ...
                    'Metric values must be a nonempty finite numeric vector.');
            end

            count = numel(values);
            meanValue = mean(values);
            stdValue = std(values);

            statistics = struct( ...
                'Count', count, ...
                'Mean', meanValue, ...
                'Std', stdValue, ...
                'Minimum', min(values), ...
                'Maximum', max(values));
        end

        function value = pearsonCorrelation(x, y)
            if numel(x) ~= numel(y) || numel(x) < 2
                error('ThesisResultsAnalysis:InvalidCorrelationInputs', ...
                    'Correlation inputs must have the same length and at least two values.');
            end
            if std(x) == 0 || std(y) == 0
                value = NaN;
                return;
            end

            correlationMatrix = corrcoef(x, y);
            value = correlationMatrix(1, 2);
        end

        function summary = groupMeanStd(keys, values)
            [uniqueKeys, ~, groupIndex] = unique(keys);
            meanValues = accumarray(groupIndex, values, [], @mean);
            stdValues = accumarray(groupIndex, values, [], @std);
            summary = table(uniqueKeys, meanValues, stdValues, 'VariableNames', {'Key', 'MeanValue', 'StdValue'});
        end

        function summary = groupMetricMeans(results, groupVariable)
            summary = groupsummary(results, groupVariable, {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs'});
        end

        function summary = groupByConstellation(results)
            workingResults = results;
            workingResults.RouteChangeDelta = ...
                workingResults.ReliableRouteChanges - workingResults.BaselineRouteChanges;
            summary = groupsummary(workingResults, ...
                {'PlaneCount', 'SatellitesPerPlane', 'NodeCount'}, {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'RouteChangeDelta'});
        end

        function summary = routeChangeStatistics(results)
            delta = results.ReliableRouteChanges - results.BaselineRouteChanges;
            summary = struct();
            summary.Baseline = ThesisResultsAnalysis.descriptiveStatistics(results.BaselineRouteChanges);
            summary.Reliable = ThesisResultsAnalysis.descriptiveStatistics(results.ReliableRouteChanges);
            summary.Delta = ThesisResultsAnalysis.descriptiveStatistics(delta);
            summary.ReliableHasFewer = sum(delta < 0);
            summary.ReliableHasMore = sum(delta > 0);
            summary.Ties = sum(delta == 0);
        end

        function summary = groupRobustnessMetrics(results, groupingVariables)
            summary = groupsummary(results, groupingVariables, {'mean', 'std'}, { ...
                'ReliableAvailabilityGain', ...
                'ReliableLatencyPenaltyMs', ...
                'EffectiveLatencyImprovementMs', ...
                'BaselineRouteChanges', ...
                'ReliableRouteChanges'});
        end

