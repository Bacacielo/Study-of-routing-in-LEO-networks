            for i = 1:height(sensitivity)
                fprintf(fid, '| %.2f | %d | %.4f +/- %.4f | %.4f +/- %.4f | %.4f +/- %.4f |\n', ...
                    sensitivity.(groupVariable)(i), ...
                    sensitivity.GroupCount(i), ...
                    sensitivity.mean_ReliableAvailabilityGain(i), ...
                    sensitivity.std_ReliableAvailabilityGain(i), ...
                    sensitivity.mean_ReliableLatencyPenaltyMs(i), ...
                    sensitivity.std_ReliableLatencyPenaltyMs(i), ...
                    sensitivity.mean_EffectiveLatencyImprovementMs(i), ...
                    sensitivity.std_EffectiveLatencyImprovementMs(i));
            end
        end


