classdef ThesisHypatiaValidation
    % THESISHYPATIAVALIDATION - Independent MATLAB checks of Hypatia data.

    methods (Static)
        function dataRoot = defaultDataRoot()
            sourceDirectory = fileparts(mfilename('fullpath'));
            projectRoot = fileparts(sourceDirectory);
            dataRoot = fullfile( ...
                projectRoot, 'reproducibility', 'hypatia', 'official_data');
        end

        function summary = analyze(dataRoot)
            if nargin < 1 || isempty(dataRoot)
                dataRoot = ThesisHypatiaValidation.defaultDataRoot();
            end
            dataRoot = ThesisHypatiaValidation.validatePathArgument( ...
                dataRoot, 'ThesisHypatiaValidation:InvalidDataRoot');
            if ~isfolder(dataRoot)
                error('ThesisHypatiaValidation:MissingDataRoot', ...
                    'Hypatia validation data directory not found: %s', dataRoot);
            end

            keys = {'kuiper_k1', 'starlink_s1', 'telesat_t1'};
            labels = ["Kuiper K1"; "Starlink S1"; "Telesat T1"];
            constellationCount = numel(keys);

            pairCount = zeros(constellationCount, 1);
            medianPathChanges = zeros(constellationCount, 1);
            meanPathChanges = zeros(constellationCount, 1);
            p90PathChanges = zeros(constellationCount, 1);
            p95PathChanges = zeros(constellationCount, 1);
            fractionAtLeast7 = zeros(constellationCount, 1);
            medianRttRangeMs = zeros(constellationCount, 1);
            meanRttRangeMs = zeros(constellationCount, 1);
            p90RttRangeMs = zeros(constellationCount, 1);
            p95RttRangeMs = zeros(constellationCount, 1);
            minimumRttRangeMs = zeros(constellationCount, 1);
            maximumRttRangeMs = zeros(constellationCount, 1);
            ecdf = struct();

            for constellationIndex = 1:constellationCount
                key = keys{constellationIndex};
                constellationDirectory = fullfile(dataRoot, key);
                pathEcdf = ThesisHypatiaValidation.readEcdf( ...
                    fullfile(constellationDirectory, ...
                    'ecdf_pairs_num_path_changes.txt'), 1);
                rttEcdf = ThesisHypatiaValidation.readEcdf( ...
                    fullfile(constellationDirectory, ...
                    'ecdf_pairs_max_minus_min_rtt_ns.txt'), 1e-6);

                pathStatistics = ThesisHypatiaValidation.summarizeValues( ...
                    pathEcdf.Values);
                rttStatistics = ThesisHypatiaValidation.summarizeValues( ...
                    rttEcdf.Values);

                pairCount(constellationIndex) = pathStatistics.Count;
                if rttStatistics.Count ~= pathStatistics.Count
                    error('ThesisHypatiaValidation:PairCountMismatch', ...
                        ['Path-change and RTT ECDFs have different sample ' ...
                        'counts for %s.'], labels(constellationIndex));
                end
                medianPathChanges(constellationIndex) = pathStatistics.Median;
                meanPathChanges(constellationIndex) = pathStatistics.Mean;
                p90PathChanges(constellationIndex) = pathStatistics.P90;
                p95PathChanges(constellationIndex) = pathStatistics.P95;
                fractionAtLeast7(constellationIndex) = ...
                    mean(pathEcdf.Values >= 7);
                medianRttRangeMs(constellationIndex) = rttStatistics.Median;
                meanRttRangeMs(constellationIndex) = rttStatistics.Mean;
                p90RttRangeMs(constellationIndex) = rttStatistics.P90;
                p95RttRangeMs(constellationIndex) = rttStatistics.P95;
                minimumRttRangeMs(constellationIndex) = rttStatistics.Minimum;
                maximumRttRangeMs(constellationIndex) = rttStatistics.Maximum;

                ecdf.(key) = struct( ...
                    'Label', labels(constellationIndex), ...
                    'PathChanges', pathEcdf, ...
                    'RttRangeMs', rttEcdf);
            end

            resultTable = table( ...
                labels, pairCount, medianPathChanges, meanPathChanges, ...
                p90PathChanges, p95PathChanges, fractionAtLeast7, ...
                medianRttRangeMs, meanRttRangeMs, p90RttRangeMs, ...
                p95RttRangeMs, minimumRttRangeMs, maximumRttRangeMs, ...
                'VariableNames', { ...
                'Constellation', ...
                'PairCount', ...
                'MedianPathChanges', ...
                'MeanPathChanges', ...
                'P90PathChanges', ...
                'P95PathChanges', ...
                'FractionAtLeast7PathChanges', ...
                'MedianRttRangeMs', ...
                'MeanRttRangeMs', ...
                'P90RttRangeMs', ...
                'P95RttRangeMs', ...
                'MinimumRttRangeMs', ...
                'MaximumRttRangeMs'});

            summary = struct( ...
                'Source', "Official Hypatia IMC 2020 v1 release", ...
                'HypatiaCommit', ...
                "0ac531c313eba2335f6344b46347140c3a0d4230", ...
                'DurationSeconds', 200, ...
                'SnapshotIntervalMs', 100, ...
                'GroundStationCount', 100, ...
                'Table', resultTable, ...
                'Ecdf', ecdf);
            summary.PaperAnchorsVerified = ...
                ThesisHypatiaValidation.verifyPaperAnchors(summary);
        end

        function verified = verifyPaperAnchors(summary)
            if ~isstruct(summary) || ~isfield(summary, 'Table') || ...
                    ~istable(summary.Table)
                error('ThesisHypatiaValidation:InvalidSummary', ...
                    'Summary must contain the Hypatia validation table.');
            end

            results = summary.Table;
            expectedLabels = ["Kuiper K1"; "Starlink S1"; "Telesat T1"];
            expectedMedians = [4; 4; 2];
            if height(results) ~= 3 || ...
                    ~isequal(results.Constellation, expectedLabels) || ...
                    any(results.PairCount ~= 4950) || ...
                    any(results.MedianPathChanges ~= expectedMedians)
                error('ThesisHypatiaValidation:PaperAnchorMismatch', ...
                    ['The ECDF data do not reproduce the published pair ' ...
                    'counts and median path-change values.']);
            end

            kuiperAndStarlink = ismember( ...
                results.Constellation, ["Kuiper K1", "Starlink S1"]);
            if any(results.FractionAtLeast7PathChanges( ...
                    kuiperAndStarlink) < 0.10)
                error('ThesisHypatiaValidation:PaperAnchorMismatch', ...
                    ['Kuiper K1 and Starlink S1 must each have at least ' ...
                    '10%% of pairs with seven or more path changes.']);
            end

            starlinkRow = results.Constellation == "Starlink S1";
            starlinkMedianRttRange = results.MedianRttRangeMs(starlinkRow);
            if starlinkMedianRttRange < 9 || starlinkMedianRttRange > 11
                error('ThesisHypatiaValidation:PaperAnchorMismatch', ...
                    ['The Starlink S1 median RTT range must be ' ...
                    'approximately 10 ms.']);
            end
            verified = true;
        end

        function artifacts = export(summary, outputDirectory)
            if nargin < 2 || isempty(outputDirectory)
                sourceDirectory = fileparts(mfilename('fullpath'));
                projectRoot = fileparts(sourceDirectory);
                outputDirectory = fullfile( ...
                    projectRoot, 'outputs', 'hypatia_validation');
            end
            outputDirectory = ThesisHypatiaValidation.validatePathArgument( ...
                outputDirectory, ...
                'ThesisHypatiaValidation:InvalidOutputDirectory');
            if ~isfolder(outputDirectory)
                mkdir(outputDirectory);
            end

            ThesisHypatiaValidation.verifyPaperAnchors(summary);
            csvPath = fullfile( ...
                outputDirectory, 'hypatia_validation_summary.csv');
            figurePath = fullfile( ...
                outputDirectory, 'hypatia_validation_ecdfs.png');
            writetable(summary.Table, csvPath);

            figureHandle = figure( ...
                'Visible', 'off', ...
                'Color', 'white', ...
                'Position', [100 100 1180 480]);
            figureCleanup = onCleanup(@() close(figureHandle));
            layout = tiledlayout(figureHandle, 1, 2, ...
                'TileSpacing', 'compact', 'Padding', 'compact');
            colors = lines(3);
            keys = {'kuiper_k1', 'starlink_s1', 'telesat_t1'};

            pathAxes = nexttile(layout);
            hold(pathAxes, 'on');
            rttAxes = nexttile(layout);
            hold(rttAxes, 'on');
            for constellationIndex = 1:numel(keys)
                item = summary.Ecdf.(keys{constellationIndex});
                stairs(pathAxes, ...
                    item.PathChanges.Values, ...
                    item.PathChanges.Probabilities, ...
                    'LineWidth', 1.8, ...
                    'Color', colors(constellationIndex, :), ...
                    'DisplayName', item.Label);
                stairs(rttAxes, ...
                    item.RttRangeMs.Values, ...
                    item.RttRangeMs.Probabilities, ...
                    'LineWidth', 1.8, ...
                    'Color', colors(constellationIndex, :), ...
                    'DisplayName', item.Label);
            end

            ThesisHypatiaValidation.formatEcdfAxes( ...
                pathAxes, 'Path changes per ground-station pair');
            ThesisHypatiaValidation.formatEcdfAxes( ...
                rttAxes, 'Maximum minus minimum RTT (ms)');
            legend(pathAxes, 'Location', 'southeast');
            legend(rttAxes, 'Location', 'southeast');
            title(pathAxes, 'Route variability');
            title(rttAxes, 'RTT variability');
            title(layout, ...
                'Official Hypatia data: 200 s, 100 ms snapshots, 4,950 pairs');

            exportgraphics(figureHandle, figurePath, 'Resolution', 200);
            clear figureCleanup;

            artifacts = struct( ...
                'OutputDirectory', outputDirectory, ...
                'SummaryCsvPath', csvPath, ...
                'EcdfFigurePath', figurePath);
        end
    end

    methods (Static, Access = private)
        function pathValue = validatePathArgument(pathValue, errorId)
            if ~(ischar(pathValue) || ...
                    (isstring(pathValue) && isscalar(pathValue)))
                error(errorId, ...
                    'Path must be a character vector or string scalar.');
            end
            pathValue = char(pathValue);
        end

        function ecdf = readEcdf(pathValue, valueScale)
            if ~isfile(pathValue)
                error('ThesisHypatiaValidation:MissingDataFile', ...
                    'Hypatia ECDF file not found: %s', pathValue);
            end
            rawData = readmatrix(pathValue, ...
                'FileType', 'text', 'Delimiter', ',');
            if ~isnumeric(rawData) || size(rawData, 2) ~= 2 || ...
                    size(rawData, 1) < 2 || any(isnan(rawData), 'all')
                error('ThesisHypatiaValidation:MalformedEcdf', ...
                    'Expected a numeric two-column ECDF file: %s', pathValue);
            end

            sentinelRows = ~isfinite(rawData(:, 1));
            if sum(sentinelRows) ~= 1 || ~sentinelRows(1) || ...
                    rawData(1, 1) ~= -Inf || rawData(1, 2) ~= 0
                error('ThesisHypatiaValidation:MalformedEcdf', ...
                    'ECDF must start with the Hypatia -Inf,0 sentinel: %s', ...
                    pathValue);
            end

            values = rawData(~sentinelRows, 1) .* valueScale;
            probabilities = rawData(~sentinelRows, 2);
            if any(~isfinite(values)) || any(~isfinite(probabilities)) || ...
                    any(diff(values) < 0) || ...
                    any(diff(probabilities) < 0) || ...
                    abs(probabilities(end) - 1) > 1e-12
                error('ThesisHypatiaValidation:InvalidEcdf', ...
                    'ECDF values or probabilities are invalid: %s', pathValue);
            end

            expectedProbabilities = ...
                (1:numel(probabilities))' ./ numel(probabilities);
            if max(abs(probabilities - expectedProbabilities)) > 1e-12
                error('ThesisHypatiaValidation:InvalidEcdf', ...
                    ['ECDF probabilities do not encode one observation per ' ...
                    'ground-station pair: %s'], pathValue);
            end
            ecdf = struct( ...
                'Values', values, ...
                'Probabilities', probabilities);
        end

        function statistics = summarizeValues(values)
            valueCount = numel(values);
            statistics = struct( ...
                'Count', valueCount, ...
                'Median', median(values), ...
                'Mean', mean(values), ...
                'P90', values(ceil(0.90 * valueCount)), ...
                'P95', values(ceil(0.95 * valueCount)), ...
                'Minimum', values(1), ...
                'Maximum', values(end));
        end

        function formatEcdfAxes(axesHandle, xLabelText)
            grid(axesHandle, 'on');
            box(axesHandle, 'on');
            xlabel(axesHandle, xLabelText);
            ylabel(axesHandle, 'ECDF');
            ylim(axesHandle, [0 1]);
            axesHandle.FontName = 'Times New Roman';
            axesHandle.FontSize = 11;
        end
    end
end
