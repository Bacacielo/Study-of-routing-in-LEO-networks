classdef ThesisStabilityStudy
    % THESISSTABILITYSTUDY - Hysteresis study for route stability.

    methods (Static)
        function result = runCase(cfg, hysteresisTolerance)
            if nargin < 1 || isempty(cfg)
                cfg = ThesisConfig.default();
            end
            if nargin < 2 || isempty(hysteresisTolerance)
                hysteresisTolerance = 0.10;
            end
            ThesisStabilityStudy.validateConfiguration( ...
                cfg, hysteresisTolerance);

            timeSteps = cfg.TimeSteps;
            [sourceNode, destinationNode] = ...
                ThesisStabilityStudy.resolveRouteEndpoints( ...
                cfg, cfg.PlaneCount * cfg.SatellitesPerPlane);
            optimalPaths = cell(1, timeSteps);
            stablePaths = cell(1, timeSteps);
            optimalLatency = zeros(1, timeSteps);
            stableLatency = zeros(1, timeSteps);
            optimalAvailability = zeros(1, timeSteps);
            stableAvailability = zeros(1, timeSteps);
            optimalEffectiveLatency = zeros(1, timeSteps);
            stableEffectiveLatency = zeros(1, timeSteps);
            previousStablePath = [];
            retainedPreviousCount = 0;
            unavailableSwitchCount = 0;
            costGapSwitchCount = 0;
            retainedRelativeCostGaps = zeros(1, timeSteps - 1);
            retainedGapCount = 0;

            for timeIndex = 1:timeSteps
                G = ThesisTopology.buildWalkerLEOSnapshot( ...
                    cfg, timeIndex);
                [stablePath, decision] = ...
                    ThesisRouting.stabilityAwarePath( ...
                    G, sourceNode, destinationNode, ...
                    cfg.ReliabilityWeight, previousStablePath, ...
                    hysteresisTolerance);
                optimalPath = decision.OptimalPath;
                optimalMetrics = ThesisMetrics.evaluatePath( ...
                    G, optimalPath);
                stableMetrics = ThesisMetrics.evaluatePath( ...
                    G, stablePath);

                optimalPaths{timeIndex} = optimalPath;
                stablePaths{timeIndex} = stablePath;
                optimalLatency(timeIndex) = optimalMetrics.LatencyMs;
                stableLatency(timeIndex) = stableMetrics.LatencyMs;
                optimalAvailability(timeIndex) = ...
                    optimalMetrics.Availability;
                stableAvailability(timeIndex) = ...
                    stableMetrics.Availability;
                optimalEffectiveLatency(timeIndex) = ...
                    optimalMetrics.EffectiveLatencyMs;
                stableEffectiveLatency(timeIndex) = ...
                    stableMetrics.EffectiveLatencyMs;

                if timeIndex > 1
                    if decision.KeptPreviousPath
                        retainedPreviousCount = ...
                            retainedPreviousCount + 1;
                        retainedGapCount = retainedGapCount + 1;
                        retainedRelativeCostGaps(retainedGapCount) = ...
                            decision.RelativeCostGap;
                    elseif decision.Reason == "PreviousPathUnavailable"
                        unavailableSwitchCount = ...
                            unavailableSwitchCount + 1;
                    elseif decision.Reason == "CostGapExceeded"
                        costGapSwitchCount = costGapSwitchCount + 1;
                    end
                end
                previousStablePath = stablePath;
            end

            optimalRouteChanges = ...
                ThesisMetrics.countRouteChanges(optimalPaths);
            stableRouteChanges = ...
                ThesisMetrics.countRouteChanges(stablePaths);
            routeChangesAvoided = ...
                optimalRouteChanges - stableRouteChanges;
            if optimalRouteChanges > 0
                routeChangeReductionRate = ...
                    routeChangesAvoided / optimalRouteChanges;
            else
                routeChangeReductionRate = 0;
            end

            optimalMeanEffectiveLatency = ...
                mean(optimalEffectiveLatency);
            stableMeanEffectiveLatency = ...
                mean(stableEffectiveLatency);
            effectiveLatencyPenalty = ...
                stableMeanEffectiveLatency - ...
                optimalMeanEffectiveLatency;
            if retainedGapCount > 0
                maximumRetainedRelativeCostGap = max( ...
                    retainedRelativeCostGaps(1:retainedGapCount));
            else
                maximumRetainedRelativeCostGap = 0;
            end

            result = struct( ...
                'Config', cfg, ...
                'HysteresisTolerance', hysteresisTolerance, ...
                'TimeSteps', timeSteps, ...
                'OptimalMeanLatencyMs', mean(optimalLatency), ...
                'StableMeanLatencyMs', mean(stableLatency), ...
                'LatencyPenaltyMs', ...
                mean(stableLatency) - mean(optimalLatency), ...
                'OptimalMeanAvailability', ...
                mean(optimalAvailability), ...
                'StableMeanAvailability', ...
                mean(stableAvailability), ...
                'AvailabilityDelta', ...
                mean(stableAvailability) - ...
                mean(optimalAvailability), ...
                'OptimalMeanEffectiveLatencyMs', ...
                optimalMeanEffectiveLatency, ...
                'StableMeanEffectiveLatencyMs', ...
                stableMeanEffectiveLatency, ...
                'EffectiveLatencyPenaltyMs', ...
                effectiveLatencyPenalty, ...
                'RelativeEffectiveLatencyPenalty', ...
                effectiveLatencyPenalty / ...
                max(optimalMeanEffectiveLatency, realmin), ...
                'OptimalRouteChanges', optimalRouteChanges, ...
                'StableRouteChanges', stableRouteChanges, ...
                'OptimalRouteChangeRate', ...
                optimalRouteChanges / (timeSteps - 1), ...
                'StableRouteChangeRate', ...
                stableRouteChanges / (timeSteps - 1), ...
                'RouteChangesAvoided', routeChangesAvoided, ...
                'RouteChangeReductionRate', ...
                routeChangeReductionRate, ...
                'PreviousPathRetentionCount', ...
                retainedPreviousCount, ...
                'PreviousPathRetentionRate', ...
                retainedPreviousCount / (timeSteps - 1), ...
                'UnavailableSwitchCount', ...
                unavailableSwitchCount, ...
                'CostGapSwitchCount', costGapSwitchCount, ...
                'MaximumRetainedRelativeCostGap', ...
                maximumRetainedRelativeCostGap, ...
                'HysteresisBoundRespected', ...
                maximumRetainedRelativeCostGap <= ...
                hysteresisTolerance + 1e-12);
        end

        function summary = summarize(results)
            requiredVariables = { ...
                'HysteresisTolerance', ...
                'StableRouteChanges', ...
                'OptimalRouteChanges', ...
                'RouteChangesAvoided', ...
                'RouteChangeReductionRate', ...
                'LatencyPenaltyMs', ...
                'AvailabilityDelta', ...
                'EffectiveLatencyPenaltyMs', ...
                'RelativeEffectiveLatencyPenalty', ...
                'PreviousPathRetentionRate', ...
                'MaximumRetainedRelativeCostGap'};
            if ~istable(results) || height(results) == 0 || ...
                    ~all(ismember(requiredVariables, ...
                    results.Properties.VariableNames))
                error('ThesisStabilityStudy:InvalidResults', ...
                    ['Stability results must be a nonempty table with ' ...
                    'all required variables.']);
            end

            grouped = groupsummary( ...
                results, 'HysteresisTolerance', {'mean', 'std'}, { ...
                'StableRouteChanges', ...
                'OptimalRouteChanges', ...
                'RouteChangesAvoided', ...
                'RouteChangeReductionRate', ...
                'LatencyPenaltyMs', ...
                'AvailabilityDelta', ...
                'EffectiveLatencyPenaltyMs', ...
                'RelativeEffectiveLatencyPenalty', ...
                'PreviousPathRetentionRate'});
            grouped.WithinOnePercentEffectiveLatencyBudget = ...
                grouped.mean_RelativeEffectiveLatencyPenalty <= 0.01;
            workingResults = results;
            workingResults.PositiveReduction = ...
                workingResults.RouteChangesAvoided > 0;
            workingResults.UnchangedReduction = ...
                workingResults.RouteChangesAvoided == 0;
            workingResults.NegativeReduction = ...
                workingResults.RouteChangesAvoided < 0;
            workingResults.WithinOnePercentCaseBudget = ...
                workingResults.RelativeEffectiveLatencyPenalty <= 0.01;
            outcomes = groupsummary( ...
                workingResults, 'HysteresisTolerance', ...
                {'sum', 'mean'}, { ...
                'PositiveReduction', ...
                'UnchangedReduction', ...
                'NegativeReduction', ...
                'WithinOnePercentCaseBudget'});
            grouped.PositiveReductionCaseCount = ...
                outcomes.sum_PositiveReduction;
            grouped.PositiveReductionCaseRate = ...
                outcomes.mean_PositiveReduction;
            grouped.UnchangedCaseCount = ...
                outcomes.sum_UnchangedReduction;
            grouped.NegativeReductionCaseCount = ...
                outcomes.sum_NegativeReduction;
            grouped.WithinOnePercentCaseRate = ...
                outcomes.mean_WithinOnePercentCaseBudget;
            grouped.ParetoEfficient = ...
                ThesisStabilityStudy.paretoFlags( ...
                grouped.mean_StableRouteChanges, ...
                grouped.mean_RelativeEffectiveLatencyPenalty);

            byDutyCycle = table();
            byReliabilityWeight = table();
            byRoutePair = table();
            bySeed = table();
            subgroupVariables = { ...
                'ContactDutyCycle', 'ReliabilityWeight', ...
                'SourceNode', 'DestinationNode', 'Seed'};
            if all(ismember( ...
                    subgroupVariables, ...
                    workingResults.Properties.VariableNames))
                subgroupMetrics = { ...
                    'RouteChangeReductionRate', ...
                    'RelativeEffectiveLatencyPenalty'};
                byDutyCycle = groupsummary( ...
                    workingResults, ...
                    {'HysteresisTolerance', 'ContactDutyCycle'}, ...
                    {'mean', 'std'}, subgroupMetrics);
                byReliabilityWeight = groupsummary( ...
                    workingResults, ...
                    {'HysteresisTolerance', 'ReliabilityWeight'}, ...
                    {'mean', 'std'}, subgroupMetrics);
                byRoutePair = groupsummary( ...
                    workingResults, ...
                    {'HysteresisTolerance', ...
                    'SourceNode', 'DestinationNode'}, ...
                    {'mean', 'std'}, subgroupMetrics);
                bySeed = groupsummary( ...
                    workingResults, ...
                    {'HysteresisTolerance', 'Seed'}, ...
                    {'mean', 'std'}, subgroupMetrics);
            end

            eligibleRows = find( ...
                grouped.WithinOnePercentEffectiveLatencyBudget);
            if isempty(eligibleRows)
                bestUnderBudget = grouped([], :);
            else
                eligible = grouped(eligibleRows, :);
                bestStableChanges = min( ...
                    eligible.mean_StableRouteChanges);
                candidates = eligible( ...
                    eligible.mean_StableRouteChanges == ...
                    bestStableChanges, :);
                [~, selectedIndex] = min( ...
                    candidates.HysteresisTolerance);
                bestUnderBudget = candidates(selectedIndex, :);
            end

            summary = struct( ...
                'RowCount', height(results), ...
                'ByHysteresisTolerance', grouped, ...
                'ByHysteresisAndDutyCycle', byDutyCycle, ...
                'ByHysteresisAndReliabilityWeight', ...
                byReliabilityWeight, ...
                'ByHysteresisAndRoutePair', byRoutePair, ...
                'ByHysteresisAndSeed', bySeed, ...
                'BestUnderOnePercentEffectiveLatencyBudget', ...
                bestUnderBudget, ...
                'AllCasesRespectHysteresisBound', ...
                all(results.MaximumRetainedRelativeCostGap <= ...
                results.HysteresisTolerance + 1e-12));
        end
    end

    methods (Static, Access = private)
        function validateConfiguration(cfg, hysteresisTolerance)
            if ~isstruct(cfg) || ~isfield(cfg, 'Profile') || ...
                    ~strcmp(cfg.Profile, 'WalkerLEO')
                error('ThesisStabilityStudy:UnsupportedConfiguration', ...
                    'Stability study requires the WalkerLEO profile.');
            end
            requiredFields = { ...
                'PlaneCount', 'SatellitesPerPlane', 'TimeSteps', ...
                'ReliabilityWeight', 'SourceNode', 'DestinationNode'};
            if ~all(isfield(cfg, requiredFields))
                error('ThesisStabilityStudy:IncompleteConfiguration', ...
                    'Stability-study configuration is incomplete.');
            end
            if ~isnumeric(cfg.TimeSteps) || ~isreal(cfg.TimeSteps) || ...
                    ~isscalar(cfg.TimeSteps) || ...
                    ~isfinite(cfg.TimeSteps) || ...
                    cfg.TimeSteps < 2 || ...
                    cfg.TimeSteps ~= floor(cfg.TimeSteps)
                error('ThesisStabilityStudy:InvalidTimeSteps', ...
                    'TimeSteps must be an integer of at least two.');
            end
            if ~isnumeric(hysteresisTolerance) || ...
                    ~isreal(hysteresisTolerance) || ...
                    ~isscalar(hysteresisTolerance) || ...
                    ~isfinite(hysteresisTolerance) || ...
                    hysteresisTolerance < 0
                error('ThesisStabilityStudy:InvalidHysteresisTolerance', ...
                    ['Hysteresis tolerance must be a finite ' ...
                    'nonnegative scalar.']);
            end
        end

        function [sourceNode, destinationNode] = ...
                resolveRouteEndpoints(cfg, nodeCount)
            sourceNode = cfg.SourceNode;
            destinationNode = cfg.DestinationNode;
            if ~isnumeric(sourceNode) || ~isscalar(sourceNode) || ...
                    ~isfinite(sourceNode) || ...
                    sourceNode ~= floor(sourceNode) || ...
                    sourceNode < 1 || sourceNode > nodeCount
                error('ThesisStabilityStudy:InvalidSourceNode', ...
                    'SourceNode must be an integer in the topology.');
            end
            if ~isnumeric(destinationNode) || ...
                    ~isscalar(destinationNode) || ...
                    ~isfinite(destinationNode) || ...
                    destinationNode ~= floor(destinationNode) || ...
                    destinationNode < 1 || ...
                    destinationNode > nodeCount
                error('ThesisStabilityStudy:InvalidDestinationNode', ...
                    'DestinationNode must be an integer in the topology.');
            end
            if sourceNode == destinationNode
                error('ThesisStabilityStudy:IdenticalEndpoints', ...
                    'Source and destination nodes must differ.');
            end
        end

        function flags = paretoFlags(routeChanges, relativePenalty)
            rowCount = numel(routeChanges);
            flags = true(rowCount, 1);
            for rowIndex = 1:rowCount
                dominates = ...
                    routeChanges <= routeChanges(rowIndex) & ...
                    relativePenalty <= relativePenalty(rowIndex) & ...
                    (routeChanges < routeChanges(rowIndex) | ...
                    relativePenalty < relativePenalty(rowIndex));
                dominates(rowIndex) = false;
                if any(dominates)
                    flags(rowIndex) = false;
                end
            end
        end
    end
end
